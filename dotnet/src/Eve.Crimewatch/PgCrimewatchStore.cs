        CancellationToken cancellationToken = default)
    {
        var targets = targetCharacterIds.Where(id => id > 0).Distinct().ToArray();
        var buyerIds = buyerOwnerIds.Where(id => id > 0).Distinct().ToArray();
        if (targets.Length == 0 || nowUnixMs <= 0)
            return [];

        List<KillRight> rights = [];
        await using var connection = await _source.OpenConnectionAsync(cancellationToken);
