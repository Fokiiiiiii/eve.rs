    public async Task<bool> MarkKillRightUsedAsync(
        long ownerCharacterId,
        long killRightId,
        long usedAtUnixMs,
        CancellationToken cancellationToken = default)
    {
        if (ownerCharacterId <= 0 || killRightId <= 0 || usedAtUnixMs <= 0)
        {
            return false;
        }
        await using var connection = await _source.OpenConnectionAsync(cancellationToken);
        await using var transaction = await connection.BeginTransactionAsync(cancellationToken);
        var changed = await Sql.ExecuteAsync(connection, transaction, Q("""
            UPDATE {schema}.kill_rights SET used_at_ms = $3
            WHERE owner_character_id = $1 AND kill_right_id = $2 AND used_at_ms IS NULL
            """), cancellationToken, ownerCharacterId, killRightId, usedAtUnixMs);
        if (changed != 1)
        {
            await transaction.RollbackAsync(cancellationToken);
            return false;
        }
        await Sql.ExecuteAsync(connection, transaction, Q("""
            UPDATE {schema}.kill_right_activations SET used_at_ms = $2
            WHERE kill_right_id = $1 AND used_at_ms IS NULL AND expires_at_ms > $2
            """), cancellationToken, killRightId, usedAtUnixMs);
        await transaction.CommitAsync(cancellationToken);
        return true;
    }


