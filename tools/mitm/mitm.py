def main(argv=None):
    parser = argparse.ArgumentParser(prog="mitm", description=__doc__.split("\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)

    def filters(command):
        command.add_argument("--service", help="only packets to or from this service (or bound object id)")
        command.add_argument("--method", help="only calls and notifications of this method")
        command.add_argument("--direction", choices=["c2s", "s2c", "both"], default="both")
        command.add_argument("--notifications-only", action="store_true", help="only notifications and session changes")

    capture = sub.add_parser("capture", help="listen, forward to the upstream server and log every packet")
    capture.add_argument("--upstream", required=True, help="host:port of the real server (eve.rs or EVE.js)")
    capture.add_argument("--listen", default="127.0.0.1:26200", help="host:port the client connects to (default 127.0.0.1:26200; the servers default to 26000 and 26100)")
    capture.add_argument("--out", help="capture file (JSON lines); the file always holds every packet, filters only shape the console")
    capture.add_argument("--quiet", action="store_true", help="do not print the readable lines")
    filters(capture)
    capture.set_defaults(run=cmd_capture)

    show = sub.add_parser("show", help="print a capture file as readable lines")
    show.add_argument("capture")
    filters(show)
    show.set_defaults(run=cmd_show)

    diff = sub.add_parser("diff", help="compare every call reply and notification in two captures")
    diff.add_argument("reference", help="the reference capture (EVE.js)")
    diff.add_argument("candidate", help="the capture to check (eve.rs)")
    diff.add_argument("--ignore-volatile", action="store_true",
                      help="ignore ids, session ids, times, random seeds and bound-object ids (see README)")
    diff.add_argument("--ignore-key-order", action="store_true",
                      help="compare marshal dictionaries by key, not by the order of their pairs (the client reads them by key)")
    diff.add_argument("--ignore-notification-order", action="store_true",
                      help="compare the server's notifications as a set, after the results (independent notices may race)")
    diff.add_argument("--first", action="store_true",
                      help="report only the first stream divergence, including exact non-volatile leaf values")
    diff.set_defaults(run=cmd_diff)

    diff_core = sub.add_parser("diff-core", help="compare every core-flow call, reply, handshake and ordered notice")
    diff_core.add_argument("reference", help="the reference capture (EVE.js)")
    diff_core.add_argument("candidate", help="the capture to check (eve.rs)")
    diff_core.add_argument("--strict-volatile", action="store_true",
                           help="compare dynamic IDs, login values, session IDs and clock values exactly")
    diff_core.add_argument("--json", action="store_true", help="print the complete machine-readable report")
    diff_core.add_argument("--all-calls", action="store_true", help="also print call rows that matched")
    diff_core.set_defaults(run=cmd_diff_core)

    diff_runs_parser = sub.add_parser(
        "diff-runs",
        help="compare two runs per server; values that vary within one server are wildcards",
    )
    diff_runs_parser.add_argument("reference_first", help="first run of the flow on the reference server (EVE.js)")
    diff_runs_parser.add_argument("reference_second", help="second run of the same flow on the reference server")
    diff_runs_parser.add_argument("candidate_first", help="first run of the flow on the candidate server (eve.rs)")
    diff_runs_parser.add_argument("candidate_second", help="second run of the same flow on the candidate server")
    diff_runs_parser.add_argument("--json", action="store_true", help="print the complete machine-readable report")
    diff_runs_parser.set_defaults(run=cmd_diff_runs)

    replay = sub.add_parser("replay", help="replay client CallReq and Notification requests against a live eve.rs server")
    replay.add_argument("capture", help="mitm JSONL capture, plain or gzip-compressed")
    replay.add_argument("--conn", required=True, type=int, help="connection number from the capture")
    replay.add_argument("--host", help="live server host:port (defaults to EVE_LIVE_HOST)")
    replay.add_argument("--timeout", type=float, default=20.0, help="maximum wait for each CallReq reply in seconds")
    replay.add_argument("--time-scale", type=float, default=1.0,
                        help="scale the capture's inter-request timing (1.0 preserves it; 0 replays immediately)")
    replay.add_argument("--allowlist", default="tools/headless-client/fixtures/live-trace-replay-allowlist.json",
                        help="JSON allowlist for known ErrorResponse signatures")
    replay.add_argument("--user", help="account name; defaults to a unique local replay account")
    replay.add_argument("--password", help="account password; defaults to a random local password")
    replay.set_defaults(run=cmd_replay)

    args = parser.parse_args(argv)
    return args.run(args)


