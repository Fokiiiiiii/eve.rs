/// <summary>What crimewatch keeps in PostgreSQL: the ship safety level of each character, and the combat timers and flags that must outlast a session.</summary>
/// <summary>Security-status event ids from the pinned eve-logic appLogConst.py.</summary>
public sealed record KillRight(
    long KillRightId,
    long OwnerCharacterId,
    long TargetCharacterId,
    long SolarSystemId,
    long CreatedAtUnixMs,
    long ExpiresAtUnixMs,
    decimal? SalePrice,
    long? RestrictedToOwnerId);


public sealed record KillRightActivation(
    long ActivationId,
    long KillRightId,
    long OwnerCharacterId,
    long TargetCharacterId,
    long ActivatorCharacterId,
    long ActivatedAtUnixMs,
    long ExpiresAtUnixMs,
    decimal PricePaid,
    string ActivationKind);

public sealed record KillRightActionResult(
    KillRight? Right,
    KillRightActivation? Activation,
    string? ErrorKey,
    decimal? RequiredAmount = null)
{
    public bool Success => ErrorKey is null && Right is not null && Activation is not null;
}

public enum KillRightPaymentResult
{
    Paid,
    InsufficientFunds,
    Failed,
}

public delegate Task<KillRightPaymentResult> KillRightPayment(
    NpgsqlConnection connection,
    NpgsqlTransaction transaction,
    long activationId,
    long buyerCharacterId,
    long sellerCharacterId,
    decimal amount,
    long timeUnixMs,
    CancellationToken cancellationToken);



