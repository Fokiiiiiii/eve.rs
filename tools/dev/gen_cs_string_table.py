#!/usr/bin/env python3
"""Generate dotnet/src/Eve.Marshal/StringTable.g.cs from the Rust string table.

The Rust file is itself generated from the JS reference (see oracle/PROVENANCE.md),
so every implementation shares one source of truth.

    python3 tools/dev/gen_cs_string_table.py [--check]
"""
import json
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parents[2]
source = (root / "crates/eve-marshal/src/string_table.rs").read_text()
entries = re.findall(r'^\s*"((?:[^"\\]|\\.)*)",\s*// (\d+)$', source, re.M)
assert [int(n) for _, n in entries] == list(range(1, len(entries) + 1)), "table is not 1..N in order"

lines = [
    "// <auto-generated> by tools/dev/gen_cs_string_table.py from crates/eve-marshal/src/string_table.rs </auto-generated>",
    "// Do not edit by hand.",
    "",
    "namespace Eve.Marshal;",
    "",
    "public static partial class StringTable",
    "{",
    "    /// <summary>Marshal string table. Wire indices are 1-based: index 1 is <c>Entries[0]</c>.</summary>",
    "    public static readonly string[] Entries =",
    "    [",
]
for text, n in entries:
    # The Rust literal escapes are a subset of JSON's; decode then re-encode for C#.
    value = json.loads(f'"{text}"')
    lines.append(f"        {json.dumps(value, ensure_ascii=False)}, // {n}")
lines += ["    ];", "}", ""]
text = "\n".join(lines)

out = root / "dotnet/src/Eve.Marshal/StringTable.g.cs"
if "--check" in sys.argv:
    sys.exit(0 if out.exists() and out.read_text() == text else 1)
out.write_text(text)
print(f"wrote {len(entries)} entries to {out.relative_to(root)}")
