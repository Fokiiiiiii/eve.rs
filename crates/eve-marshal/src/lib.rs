#![forbid(unsafe_code)]

//! EVE MachoNet marshal codec.
//!
//! Byte-compatible with the JS reference in
//! `server/src/network/tcp/utils/marshal.js`; compatibility is enforced by the
//! golden fixtures under `oracle/fixtures/marshal`, which the
//! `eve-oracle` crate replays.
//!
//! ```
//! use eve_marshal::{Value, decode, encode};
//!
//! let call = Value::Tuple(vec![Value::Int(7), Value::str("machoNet")]);
//! let bytes = encode(&call).unwrap();
//! assert_eq!(bytes[0], 0x7e);
//! assert!(decode(&bytes).is_ok());
//! ```

mod decode;
mod encode;
mod error;
mod jsnum;
mod packed_row;
// Generated by tools/oracle/genStringTable.js; keep rustfmt away from it.
#[rustfmt::skip]
mod string_table;
mod value;
mod wire;

pub use decode::{decode, decode_bytes, decode_exact, decode_exact_bytes, split_packet};
pub use encode::{encode, encode_into, encode_packet};
pub use error::{MarshalError, Result};
pub use packed_row::{columns_from_header, compress_rle, decompress_rle, descriptor_columns};
pub use string_table::STRING_TABLE;
pub use value::{Bytes, Descriptor, ObjectExKind, PackedColumn, PackedRow, SubStream, Value};
pub use wire::{MARSHAL_HEADER, dbtype, op};

/// Deepest nesting the codec accepts in either direction. The JS reference
/// only stops at the engine's stack limit; a native decoder fed by a network
/// peer needs an explicit bound.
pub const MAX_DEPTH: usize = 256;
