using System.Text;
using System.Text.RegularExpressions;
using Npgsql;

namespace Eve.Host.Xmpp;

internal sealed record XmppPlayerChannelRestriction(
    long ChannelId,
    long CharacterId,
    string Category,
    long? ExpiresAtMs,
    string Reason,
    long ByCharacterId,
    long CreatedAtMs);

internal sealed record XmppPlayerChannel(
    long Id,
    string DisplayName,
    long OwnerCharacterId,
    IReadOnlySet<long> OwnerCharacterIds,
    IReadOnlySet<long> InvitedCharacterIds,
    IReadOnlySet<long> AdminCharacterIds,
    IReadOnlySet<long> DeniedCharacterIds,
    IReadOnlySet<long> MutedCharacterIds,
    IReadOnlySet<long> AllowedCorporationIds,
    IReadOnlySet<long> DeniedCorporationIds,
    IReadOnlySet<long> AllowedAllianceIds,
    IReadOnlySet<long> DeniedAllianceIds,
    IReadOnlySet<long> TemporaryBannedCharacterIds,
    IReadOnlySet<long> TemporaryMutedCharacterIds,
    string Description,
    string Password,
    bool PasswordRequired,
    bool MembersOnly,
    bool MembersByDefault)
{
    public string RoomName => $"player_{Id.ToString(System.Globalization.CultureInfo.InvariantCulture)}";

    public bool IsOwner(long characterId) => OwnerCharacterId == characterId || OwnerCharacterIds.Contains(characterId);

    public bool IsAdministrator(long characterId) => IsOwner(characterId) || AdminCharacterIds.Contains(characterId);

    public bool Allows(long characterId, long corporationId = 0, long allianceId = 0) =>
        IsAdministrator(characterId) || InvitedCharacterIds.Contains(characterId)
        || corporationId > 0 && AllowedCorporationIds.Contains(corporationId)
        || allianceId > 0 && AllowedAllianceIds.Contains(allianceId);

    public bool IsBanned(long characterId, long corporationId = 0, long allianceId = 0) =>
        DeniedCharacterIds.Contains(characterId) || TemporaryBannedCharacterIds.Contains(characterId)
        || corporationId > 0 && DeniedCorporationIds.Contains(corporationId)
        || allianceId > 0 && DeniedAllianceIds.Contains(allianceId);

    public bool IsMuted(long characterId) => MutedCharacterIds.Contains(characterId) || TemporaryMutedCharacterIds.Contains(characterId);
}

internal sealed class XmppPlayerChannelStore
{
    public const int MaxDisplayNameBytes = 128;
    private readonly NpgsqlDataSource _source;
    private readonly string _schema;
    private readonly object _gate = new();
    private readonly Dictionary<string, XmppPlayerChannel> _channels;
    private readonly Dictionary<(long ChannelId, long CharacterId, string Category), XmppPlayerChannelRestriction> _restrictions = [];

    private XmppPlayerChannelStore(NpgsqlDataSource source, string schema, Dictionary<string, XmppPlayerChannel> channels)
    {
        _source = source;
        _schema = schema;
        _channels = channels;
    }

    public static async Task<XmppPlayerChannelStore> OpenAsync(NpgsqlDataSource source, string schema, CancellationToken cancellationToken = default)
    {
        if (!Regex.IsMatch(schema, "^[a-z_][a-z0-9_]{0,62}$"))
            throw new ArgumentException($"not a usable schema name: {schema}", nameof(schema));
        await using (var createSchema = source.CreateCommand($"CREATE SCHEMA IF NOT EXISTS {schema}"))
            await createSchema.ExecuteNonQueryAsync(cancellationToken);
        await using (var createTable = source.CreateCommand($"CREATE TABLE IF NOT EXISTS {schema}.player_channels (channel_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, display_name text NOT NULL CHECK (char_length(display_name) BETWEEN 1 AND 128), owner_character_id bigint NOT NULL CHECK (owner_character_id > 0), invited_character_ids bigint[] NOT NULL DEFAULT '{{}}', created_ms bigint NOT NULL DEFAULT ((extract(epoch FROM clock_timestamp()) * 1000)::bigint))"))
            await createTable.ExecuteNonQueryAsync(cancellationToken);
        await using (var configureTable = source.CreateCommand($"ALTER TABLE {schema}.player_channels ADD COLUMN IF NOT EXISTS owner_character_ids bigint[] NOT NULL DEFAULT '{{}}', ADD COLUMN IF NOT EXISTS admin_character_ids bigint[] NOT NULL DEFAULT '{{}}', ADD COLUMN IF NOT EXISTS denied_character_ids bigint[] NOT NULL DEFAULT '{{}}', ADD COLUMN IF NOT EXISTS muted_character_ids bigint[] NOT NULL DEFAULT '{{}}', ADD COLUMN IF NOT EXISTS allowed_corporation_ids bigint[] NOT NULL DEFAULT '{{}}', ADD COLUMN IF NOT EXISTS denied_corporation_ids bigint[] NOT NULL DEFAULT '{{}}', ADD COLUMN IF NOT EXISTS allowed_alliance_ids bigint[] NOT NULL DEFAULT '{{}}', ADD COLUMN IF NOT EXISTS denied_alliance_ids bigint[] NOT NULL DEFAULT '{{}}', ADD COLUMN IF NOT EXISTS description text NOT NULL DEFAULT '', ADD COLUMN IF NOT EXISTS password text NOT NULL DEFAULT '', ADD COLUMN IF NOT EXISTS password_required boolean NOT NULL DEFAULT false, ADD COLUMN IF NOT EXISTS members_only boolean NOT NULL DEFAULT false, ADD COLUMN IF NOT EXISTS members_by_default boolean NOT NULL DEFAULT true"))
            await configureTable.ExecuteNonQueryAsync(cancellationToken);
        await using (var createRestrictions = source.CreateCommand($"CREATE TABLE IF NOT EXISTS {schema}.player_channel_restrictions (channel_id bigint NOT NULL REFERENCES {schema}.player_channels(channel_id) ON DELETE CASCADE, character_id bigint NOT NULL CHECK (character_id > 0), category text NOT NULL CHECK (category IN ('ban','mute')), expires_at_ms bigint, reason text NOT NULL DEFAULT '', by_character_id bigint NOT NULL DEFAULT 0, created_at_ms bigint NOT NULL, PRIMARY KEY (channel_id, character_id, category))"))
            await createRestrictions.ExecuteNonQueryAsync(cancellationToken);

        var channels = new Dictionary<string, XmppPlayerChannel>(StringComparer.Ordinal);
        await using (var command = source.CreateCommand($"SELECT channel_id,display_name,owner_character_id,owner_character_ids,invited_character_ids,admin_character_ids,denied_character_ids,muted_character_ids,allowed_corporation_ids,denied_corporation_ids,allowed_alliance_ids,denied_alliance_ids,description,password,password_required,members_only,members_by_default FROM {schema}.player_channels ORDER BY channel_id"))
        await using (var reader = await command.ExecuteReaderAsync(cancellationToken))
        {
            while (await reader.ReadAsync(cancellationToken))
            {
                var id = reader.GetInt64(0);
                var roomName = $"player_{id.ToString(System.Globalization.CultureInfo.InvariantCulture)}";
                var channel = ReadChannel(reader);
                channels.Add(roomName, channel);
            }
        }
        var store = new XmppPlayerChannelStore(source, schema, channels);
        await using (var command = source.CreateCommand($"SELECT channel_id,character_id,category,expires_at_ms,reason,by_character_id,created_at_ms FROM {schema}.player_channel_restrictions"))
        await using (var reader = await command.ExecuteReaderAsync(cancellationToken))
        {
            while (await reader.ReadAsync(cancellationToken))
            {
                var restriction = new XmppPlayerChannelRestriction(
                    reader.GetInt64(0), reader.GetInt64(1), reader.GetString(2),
                    reader.IsDBNull(3) ? null : reader.GetInt64(3), reader.GetString(4), reader.GetInt64(5), reader.GetInt64(6));
                store._restrictions[(restriction.ChannelId, restriction.CharacterId, restriction.Category)] = restriction;
            }
        }
        return store;
    }

    public async Task<XmppPlayerChannel?> CreateAsync(long ownerCharacterId, string displayName, CancellationToken cancellationToken = default)
    {
        displayName = displayName.Trim();
        if (ownerCharacterId <= 0 || displayName.Length == 0 || Encoding.UTF8.GetByteCount(displayName) > MaxDisplayNameBytes
            || displayName.Any(char.IsControl))
            return null;

        await using var command = _source.CreateCommand($"INSERT INTO {_schema}.player_channels(display_name,owner_character_id) VALUES ($1,$2) RETURNING channel_id");
        command.Parameters.AddWithValue(displayName);
        command.Parameters.AddWithValue(ownerCharacterId);
        var id = (long)(await command.ExecuteScalarAsync(cancellationToken) ?? throw new InvalidOperationException("player channel insert returned no id"));
        var channel = new XmppPlayerChannel(id, displayName, ownerCharacterId,
            new HashSet<long>(), new HashSet<long>(), new HashSet<long>(), new HashSet<long>(), new HashSet<long>(),
            new HashSet<long>(), new HashSet<long>(), new HashSet<long>(), new HashSet<long>(),
            new HashSet<long>(), new HashSet<long>(),
            "", "", false, false, true);
        lock (_gate)
            _channels.Add(channel.RoomName, channel);
        return channel;
    }

    public async Task<bool> SetOwnerAsync(string roomName, long ownerCharacterId, CancellationToken cancellationToken = default)
    {
        if (ownerCharacterId <= 0 || !TryId(roomName, out var id)) return false;
        await using var command = _source.CreateCommand($"UPDATE {_schema}.player_channels SET owner_character_id=$2, owner_character_ids=array_remove(owner_character_ids,$2), invited_character_ids=array_remove(invited_character_ids,$2), admin_character_ids=array_remove(admin_character_ids,$2), denied_character_ids=array_remove(denied_character_ids,$2) WHERE channel_id=$1");
        command.Parameters.AddWithValue(id);
        command.Parameters.AddWithValue(ownerCharacterId);
        if (await command.ExecuteNonQueryAsync(cancellationToken) != 1) return false;
        lock (_gate)
        {
            if (_channels.TryGetValue(roomName, out var channel))
            {
                var invited = channel.InvitedCharacterIds.ToHashSet();
                invited.Remove(ownerCharacterId);
                var owners = channel.OwnerCharacterIds.ToHashSet();
                owners.Remove(ownerCharacterId);
                var admins = channel.AdminCharacterIds.ToHashSet();
                admins.Remove(ownerCharacterId);
                var denied = channel.DeniedCharacterIds.ToHashSet();
                denied.Remove(ownerCharacterId);
                _channels[roomName] = channel with
                {
                    OwnerCharacterId = ownerCharacterId,
                    OwnerCharacterIds = owners,
                    InvitedCharacterIds = invited,
                    AdminCharacterIds = admins,
                    DeniedCharacterIds = denied,
                };
            }
        }
        return true;
    }

    public async Task<XmppPlayerChannel?> SetAffiliationAsync(
        string roomName,
        long characterId,
        string affiliation,
        string reason = "",
        long byCharacterId = 0,
        CancellationToken cancellationToken = default)
    {
        if (characterId <= 0 || !TryId(roomName, out var id)
            || affiliation is not ("owner" or "admin" or "member" or "outcast" or "none"))
            return null;
        const string sql = """
            UPDATE __SCHEMA__.player_channels SET
                owner_character_id = CASE
                    WHEN $2=owner_character_id AND $3 IN ('admin','member','outcast','none') AND cardinality(owner_character_ids)>0 THEN owner_character_ids[1]
                    ELSE owner_character_id END,
                owner_character_ids = CASE
                    WHEN $3='owner' AND $2<>owner_character_id AND NOT ($2=ANY(owner_character_ids)) THEN array_append(owner_character_ids,$2)
                    WHEN $3 IN ('admin','member','outcast','none') THEN array_remove(owner_character_ids,$2)
                    ELSE owner_character_ids END,
                admin_character_ids = CASE
                    WHEN $3='admin' AND ( $2<>owner_character_id OR cardinality(owner_character_ids)>0 ) AND NOT ($2=ANY(admin_character_ids)) THEN array_append(admin_character_ids,$2)
                    WHEN $3 IN ('owner','member','outcast','none') THEN array_remove(admin_character_ids,$2)
                    ELSE admin_character_ids END,
                invited_character_ids = CASE
                    WHEN $3='member' AND ( $2<>owner_character_id OR cardinality(owner_character_ids)>0 ) AND NOT ($2=ANY(invited_character_ids)) THEN array_append(invited_character_ids,$2)
                    WHEN $3 IN ('owner','admin','outcast','none') THEN array_remove(invited_character_ids,$2)
                    ELSE invited_character_ids END,
                denied_character_ids = CASE
                    WHEN $3='outcast' AND ( $2<>owner_character_id OR cardinality(owner_character_ids)>0 ) AND NOT ($2=ANY(denied_character_ids)) THEN array_append(denied_character_ids,$2)
                    WHEN $3 IN ('owner','admin','member','none') THEN array_remove(denied_character_ids,$2)
                    ELSE denied_character_ids END
            WHERE channel_id=$1
            RETURNING channel_id,display_name,owner_character_id,owner_character_ids,invited_character_ids,admin_character_ids,denied_character_ids,muted_character_ids,allowed_corporation_ids,denied_corporation_ids,allowed_alliance_ids,denied_alliance_ids,description,password,password_required,members_only,members_by_default
            """;
        await using var connection = await _source.OpenConnectionAsync(cancellationToken);
        await using var transaction = await connection.BeginTransactionAsync(cancellationToken);
        XmppPlayerChannel channel;
        await using (var command = connection.CreateCommand())
        {
            command.CommandText = sql.Replace("__SCHEMA__", _schema, StringComparison.Ordinal);
            command.Transaction = transaction;
            command.Parameters.AddWithValue(id);
            command.Parameters.AddWithValue(characterId);
            command.Parameters.AddWithValue(affiliation);
            await using var reader = await command.ExecuteReaderAsync(cancellationToken);
            if (!await reader.ReadAsync(cancellationToken)) return null;
            channel = ReadChannel(reader);
        }
        var nowUnixMs = DateTimeOffset.UtcNow.ToUnixTimeMilliseconds();
        if (affiliation == "outcast")
            await UpsertPermanentRestrictionAsync(connection, transaction, id, characterId, "ban", reason,
                byCharacterId, nowUnixMs, cancellationToken).ConfigureAwait(false);
        else
            await DeletePermanentOrExpiredRestrictionAsync(connection, transaction, id, characterId, "ban",
                nowUnixMs, cancellationToken).ConfigureAwait(false);
        var restriction = await ReadRestrictionAsync(connection, transaction, id, characterId, "ban", cancellationToken)
            .ConfigureAwait(false);
        await transaction.CommitAsync(cancellationToken).ConfigureAwait(false);
        lock (_gate)
        {
            _channels[roomName] = channel;
            if (restriction is not null) _restrictions[(id, characterId, "ban")] = restriction;
            else _restrictions.Remove((id, characterId, "ban"));
        }
        return channel;
    }

    public async Task<XmppPlayerChannel?> SetOrganizationAffiliationAsync(
        string roomName,
        long organizationId,
        bool alliance,
        string affiliation,
        CancellationToken cancellationToken = default)
    {
        if (organizationId <= 0 || !TryId(roomName, out var id)
            || affiliation is not ("member" or "outcast" or "none"))
            return null;

        var allowedColumn = alliance ? "allowed_alliance_ids" : "allowed_corporation_ids";
        var deniedColumn = alliance ? "denied_alliance_ids" : "denied_corporation_ids";
        var sql = $"""
            UPDATE {_schema}.player_channels SET
                {allowedColumn}=CASE
                    WHEN $3='member' AND NOT ($2=ANY({allowedColumn})) THEN array_append({allowedColumn},$2)
                    WHEN $3 IN ('outcast','none') THEN array_remove({allowedColumn},$2)
                    ELSE {allowedColumn} END,
                {deniedColumn}=CASE
                    WHEN $3='outcast' AND NOT ($2=ANY({deniedColumn})) THEN array_append({deniedColumn},$2)
                    WHEN $3 IN ('member','none') THEN array_remove({deniedColumn},$2)
                    ELSE {deniedColumn} END
            WHERE channel_id=$1
            RETURNING channel_id,display_name,owner_character_id,owner_character_ids,invited_character_ids,admin_character_ids,denied_character_ids,muted_character_ids,allowed_corporation_ids,denied_corporation_ids,allowed_alliance_ids,denied_alliance_ids,description,password,password_required,members_only,members_by_default
            """;
        await using var command = _source.CreateCommand(sql);
        command.Parameters.AddWithValue(id);
        command.Parameters.AddWithValue(organizationId);
        command.Parameters.AddWithValue(affiliation);
        await using var reader = await command.ExecuteReaderAsync(cancellationToken);
        if (!await reader.ReadAsync(cancellationToken)) return null;
        var channel = ReadChannel(reader);
        lock (_gate) _channels[roomName] = channel;
        return channel;
    }

    public async Task<XmppPlayerChannel?> SetRoleAsync(
        string roomName,
        long characterId,
        string role,
        string reason = "",
        long byCharacterId = 0,
        CancellationToken cancellationToken = default)
    {
        if (characterId <= 0 || !TryId(roomName, out var id) || role is not ("visitor" or "participant"))
            return null;
        var operation = role == "visitor" ? "array_append(muted_character_ids,$2)" : "array_remove(muted_character_ids,$2)";
        var condition = role == "visitor" ? "NOT ($2=ANY(muted_character_ids))" : "TRUE";
        var sql = $"UPDATE {_schema}.player_channels SET muted_character_ids=CASE WHEN {condition} THEN {operation} ELSE muted_character_ids END WHERE channel_id=$1 RETURNING channel_id,display_name,owner_character_id,owner_character_ids,invited_character_ids,admin_character_ids,denied_character_ids,muted_character_ids,allowed_corporation_ids,denied_corporation_ids,allowed_alliance_ids,denied_alliance_ids,description,password,password_required,members_only,members_by_default";
        await using var connection = await _source.OpenConnectionAsync(cancellationToken);
        await using var transaction = await connection.BeginTransactionAsync(cancellationToken);
        XmppPlayerChannel channel;
        await using (var command = connection.CreateCommand())
        {
            command.CommandText = sql;
            command.Transaction = transaction;
            command.Parameters.AddWithValue(id);
            command.Parameters.AddWithValue(characterId);
            await using var reader = await command.ExecuteReaderAsync(cancellationToken);
            if (!await reader.ReadAsync(cancellationToken)) return null;
            channel = ReadChannel(reader);
        }
        var nowUnixMs = DateTimeOffset.UtcNow.ToUnixTimeMilliseconds();
        if (role == "visitor")
            await UpsertPermanentRestrictionAsync(connection, transaction, id, characterId, "mute", reason,
                byCharacterId, nowUnixMs, cancellationToken).ConfigureAwait(false);
        else
            await DeleteRestrictionAsync(connection, transaction, id, characterId, "mute", cancellationToken).ConfigureAwait(false);
        var restriction = await ReadRestrictionAsync(connection, transaction, id, characterId, "mute", cancellationToken)
            .ConfigureAwait(false);
        await transaction.CommitAsync(cancellationToken).ConfigureAwait(false);
        lock (_gate)
        {
            _channels[roomName] = channel;
            if (restriction is not null) _restrictions[(id, characterId, "mute")] = restriction;
            else _restrictions.Remove((id, characterId, "mute"));
        }
        return channel;
    }

    public async Task<XmppPlayerChannelRestriction?> SetTemporaryRestrictionAsync(
        string roomName,
        long characterId,
        string category,
        long durationSeconds,
        string reason,
        long byCharacterId,
        CancellationToken cancellationToken = default)
    {
        if (characterId <= 0 || !TryId(roomName, out var id) || category is not ("ban" or "mute")
            || durationSeconds is < 1 or > 315_360_000 || byCharacterId < 0
            || reason.Length > 256 || reason.Any(character => char.IsControl(character) && character is not '\n' and not '\t'))
            return null;

        var nowUnixMs = DateTimeOffset.UtcNow.ToUnixTimeMilliseconds();
        var expiresAtMs = checked(nowUnixMs + durationSeconds * 1000);
        XmppPlayerChannelRestriction? previous;
        lock (_gate) _restrictions.TryGetValue((id, characterId, category), out previous);
        if (reason.Length == 0 && previous is { Reason.Length: > 0 }) reason = previous.Reason;
        var restriction = new XmppPlayerChannelRestriction(id, characterId, category, expiresAtMs, reason,
            byCharacterId, nowUnixMs);

        var arrayColumn = category == "ban" ? "denied_character_ids" : "muted_character_ids";
        await using var connection = await _source.OpenConnectionAsync(cancellationToken);
        await using var transaction = await connection.BeginTransactionAsync(cancellationToken);
        await using (var update = connection.CreateCommand())
        {
            update.CommandText = $"UPDATE {_schema}.player_channels SET {arrayColumn}=array_remove({arrayColumn},$2) WHERE channel_id=$1";
            update.Transaction = transaction;
            update.Parameters.AddWithValue(id);
            update.Parameters.AddWithValue(characterId);
            if (await update.ExecuteNonQueryAsync(cancellationToken).ConfigureAwait(false) != 1) return null;
        }
        await UpsertRestrictionAsync(connection, transaction, id, characterId, category, expiresAtMs, reason,
            byCharacterId, nowUnixMs, cancellationToken).ConfigureAwait(false);
        await transaction.CommitAsync(cancellationToken).ConfigureAwait(false);

        lock (_gate)
        {
            _restrictions[(id, characterId, category)] = restriction;
            if (_channels.TryGetValue(roomName, out var channel))
            {
                if (category == "ban")
                {
                    var denied = channel.DeniedCharacterIds.ToHashSet();
                    denied.Remove(characterId);
                    _channels[roomName] = channel with { DeniedCharacterIds = denied };
                }
                else
                {
                    var muted = channel.MutedCharacterIds.ToHashSet();
                    muted.Remove(characterId);
                    _channels[roomName] = channel with { MutedCharacterIds = muted };
                }
            }
        }
        return restriction;
    }

    public async Task DeleteRestrictionAsync(
        string roomName,
        long characterId,
        string category,
        CancellationToken cancellationToken = default)
    {
        if (characterId <= 0 || !TryId(roomName, out var id) || category is not ("ban" or "mute")) return;
        await using var connection = await _source.OpenConnectionAsync(cancellationToken);
        await using var command = connection.CreateCommand();
        command.CommandText = $"DELETE FROM {_schema}.player_channel_restrictions WHERE channel_id=$1 AND character_id=$2 AND category=$3";
        command.Parameters.AddWithValue(id);
        command.Parameters.AddWithValue(characterId);
        command.Parameters.AddWithValue(category);
        await command.ExecuteNonQueryAsync(cancellationToken).ConfigureAwait(false);
        lock (_gate) _restrictions.Remove((id, characterId, category));
    }

    public async Task<IReadOnlyList<XmppPlayerChannelRestriction>> ListTemporaryRestrictionsAsync(
        string roomName,
        string category,
        CancellationToken cancellationToken = default)
    {
        if (!TryId(roomName, out var id) || category is not ("ban" or "mute")) return [];
        var nowUnixMs = DateTimeOffset.UtcNow.ToUnixTimeMilliseconds();
        var result = new List<XmppPlayerChannelRestriction>();
        await using var command = _source.CreateCommand($"SELECT channel_id,character_id,category,expires_at_ms,reason,by_character_id,created_at_ms FROM {_schema}.player_channel_restrictions WHERE channel_id=$1 AND category=$2 AND expires_at_ms>$3 ORDER BY expires_at_ms,character_id");
        command.Parameters.AddWithValue(id);
        command.Parameters.AddWithValue(category);
        command.Parameters.AddWithValue(nowUnixMs);
        await using var reader = await command.ExecuteReaderAsync(cancellationToken).ConfigureAwait(false);
        while (await reader.ReadAsync(cancellationToken).ConfigureAwait(false))
            result.Add(new XmppPlayerChannelRestriction(reader.GetInt64(0), reader.GetInt64(1), reader.GetString(2),
                reader.GetInt64(3), reader.GetString(4), reader.GetInt64(5), reader.GetInt64(6)));
        return result;
    }

    private async Task UpsertRestrictionAsync(
        Npgsql.NpgsqlConnection connection,
        Npgsql.NpgsqlTransaction transaction,
        long channelId,
        long characterId,
        string category,
        long? expiresAtMs,
        string reason,
        long byCharacterId,
        long createdAtMs,
        CancellationToken cancellationToken)
    {
        await using var command = connection.CreateCommand();
        command.CommandText = $"INSERT INTO {_schema}.player_channel_restrictions (channel_id,character_id,category,expires_at_ms,reason,by_character_id,created_at_ms) VALUES ($1,$2,$3,$4,$5,$6,$7) ON CONFLICT (channel_id,character_id,category) DO UPDATE SET expires_at_ms=EXCLUDED.expires_at_ms,reason=EXCLUDED.reason,by_character_id=EXCLUDED.by_character_id,created_at_ms=EXCLUDED.created_at_ms";
        command.Transaction = transaction;
        command.Parameters.AddWithValue(channelId);
        command.Parameters.AddWithValue(characterId);
        command.Parameters.AddWithValue(category);
        command.Parameters.Add(new Npgsql.NpgsqlParameter
        {
            NpgsqlDbType = NpgsqlTypes.NpgsqlDbType.Bigint,
            Value = expiresAtMs is { } expires ? expires : DBNull.Value,
        });
        command.Parameters.AddWithValue(reason);
        command.Parameters.AddWithValue(byCharacterId);
        command.Parameters.AddWithValue(createdAtMs);
        await command.ExecuteNonQueryAsync(cancellationToken).ConfigureAwait(false);
    }

    private async Task UpsertPermanentRestrictionAsync(
        Npgsql.NpgsqlConnection connection,
        Npgsql.NpgsqlTransaction transaction,
        long channelId,
        long characterId,
        string category,
        string reason,
        long byCharacterId,
        long createdAtMs,
        CancellationToken cancellationToken)
    {
        await using var command = connection.CreateCommand();
        command.CommandText = $"INSERT INTO {_schema}.player_channel_restrictions (channel_id,character_id,category,expires_at_ms,reason,by_character_id,created_at_ms) VALUES ($1,$2,$3,NULL,$4,$5,$6) ON CONFLICT (channel_id,character_id,category) DO UPDATE SET expires_at_ms=NULL,reason=EXCLUDED.reason,by_character_id=EXCLUDED.by_character_id,created_at_ms=EXCLUDED.created_at_ms WHERE {_schema}.player_channel_restrictions.expires_at_ms IS NULL OR {_schema}.player_channel_restrictions.expires_at_ms <= $7";
        command.Transaction = transaction;
        command.Parameters.AddWithValue(channelId);
        command.Parameters.AddWithValue(characterId);
        command.Parameters.AddWithValue(category);
        command.Parameters.AddWithValue(reason);
        command.Parameters.AddWithValue(byCharacterId);
        command.Parameters.AddWithValue(createdAtMs);
        command.Parameters.AddWithValue(createdAtMs);
        await command.ExecuteNonQueryAsync(cancellationToken).ConfigureAwait(false);
    }

    private async Task DeletePermanentOrExpiredRestrictionAsync(
        Npgsql.NpgsqlConnection connection,
        Npgsql.NpgsqlTransaction transaction,
        long channelId,
        long characterId,
        string category,
        long nowUnixMs,
        CancellationToken cancellationToken)
    {
        await using var command = connection.CreateCommand();
        command.CommandText = $"DELETE FROM {_schema}.player_channel_restrictions WHERE channel_id=$1 AND character_id=$2 AND category=$3 AND (expires_at_ms IS NULL OR expires_at_ms <= $4)";
        command.Transaction = transaction;
        command.Parameters.AddWithValue(channelId);
        command.Parameters.AddWithValue(characterId);
        command.Parameters.AddWithValue(category);
        command.Parameters.AddWithValue(nowUnixMs);
        await command.ExecuteNonQueryAsync(cancellationToken).ConfigureAwait(false);
    }

    private async Task<XmppPlayerChannelRestriction?> ReadRestrictionAsync(
        Npgsql.NpgsqlConnection connection,
        Npgsql.NpgsqlTransaction transaction,
        long channelId,
        long characterId,
        string category,
        CancellationToken cancellationToken)
    {
        await using var command = connection.CreateCommand();
        command.CommandText = $"SELECT channel_id,character_id,category,expires_at_ms,reason,by_character_id,created_at_ms FROM {_schema}.player_channel_restrictions WHERE channel_id=$1 AND character_id=$2 AND category=$3";
        command.Transaction = transaction;
        command.Parameters.AddWithValue(channelId);
        command.Parameters.AddWithValue(characterId);
        command.Parameters.AddWithValue(category);
        await using var reader = await command.ExecuteReaderAsync(cancellationToken).ConfigureAwait(false);
        return await reader.ReadAsync(cancellationToken).ConfigureAwait(false)
            ? new XmppPlayerChannelRestriction(reader.GetInt64(0), reader.GetInt64(1), reader.GetString(2),
                reader.IsDBNull(3) ? null : reader.GetInt64(3), reader.GetString(4), reader.GetInt64(5), reader.GetInt64(6))
            : null;
    }

