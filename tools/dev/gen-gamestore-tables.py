#!/usr/bin/env python3
"""Generate dotnet/src/Eve.GameStore/GameStoreTables.g.cs from the gameStore fixtures.

    tools/dev/gen-gamestore-tables.py            write the file
    tools/dev/gen-gamestore-tables.py --check    fail if the file is stale

The table sets come from the reference implementation (oracle/fixtures/gamestore/
tables.json); a C# test also compares them with the fixture, so a re-sync that
forgets to regenerate is caught either way.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "oracle/fixtures/gamestore/tables.json"
OUT = ROOT / "dotnet/src/Eve.GameStore/GameStoreTables.g.cs"

def q(text: str) -> str:
    return json.dumps(text)

def render() -> str:
    data = json.loads(SRC.read_text())
    lines = [
        "// <auto-generated> by tools/dev/gen-gamestore-tables.py from oracle/fixtures/gamestore/tables.json </auto-generated>",
        "// Do not edit: regenerate with the script.",
        "",
        "namespace Eve.GameStore;",
        "",
        "public static partial class GameStoreTables",
        "{",
        "    /// <summary>Tables persisted through the store (SQLITE_TABLES in the reference server).</summary>",
        "    public static readonly IReadOnlyList<string> RuntimeTables =",
        "    [",
    ]
    lines += [f"        {q(t)}," for t in data["runtimeTables"]]
    lines += [
        "    ];",
        "",
        "    /// <summary>Tables whose top-level groups are stored one row per entity (ROW_GROUPS).</summary>",
        "    public static readonly IReadOnlyDictionary<string, IReadOnlyList<string>> RowGroups =",
        "        new Dictionary<string, IReadOnlyList<string>>",
        "        {",
    ]
    for table, groups in data["rowGroups"].items():
        inner = ", ".join(q(g) for g in groups)
        lines.append(f"            [{q(table)}] = [{inner}],")
    lines += ["        };", "}", ""]
    return "\n".join(lines)

def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"stale: {OUT.relative_to(ROOT)}", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0

sys.exit(main())
