#!/usr/bin/env node
// Writes oracle/fixtures/npc/spawn_plans.json: what the EVE.js reference's resolveNpcSpawnPlan makes of what a player types after /npc (which profile or
// pool, the error and the suggestions, the profiles a pool rolls for the numbers it was given), so that the port in dotnet/src/Eve.Npc/NpcSelector.cs is
// checked against it. The reference also generates NPCs in code (capital, drifter, abyssal, mining, empire-security catalogs); those are switched off
// here, because the port has the authored tables only.
//
//   SDE=.cache/sde/eve-online-static-data-<build>-jsonl EVEJS_DATA_ROOT=$PWD/.cache/ref EVEJS_GAMESTORE_DATA_DIR=$PWD/.cache/ref/gameStore/data \
//     node tools/dev/gen-npc-selection-fixture.js
"use strict";

const fs = require("fs");
const path = require("path");

const EVEJS = process.env.EVEJS || "/home/user/evejs-v0.12.9";
const OUT = path.join(__dirname, "..", "..", "oracle", "fixtures", "npc", "spawn_plans.json");
const npcDir = path.join(EVEJS, "server/src/space/npc");

// switch off the generated catalogs before npcData reads them
for (const [file, names] of [
  ["capitals/capitalNpcCatalog", ["getCapitalNpcGeneratedRows"]],
  ["trigDrifter/trigDrifterNpcCatalog", ["getTrigDrifterGeneratedRows"]],
  ["abyssal/abyssalNpcCatalog", ["getAbyssalNpcGeneratedRows"]],
  ["empireSecurity/empireSecurityNpcCatalog", ["getEmpireSecurityGeneratedRows"]],
  ["miningNpcCatalog", ["getMiningNpcGeneratedRows"]],
]) {
  const mod = require(path.join(npcDir, file));
  for (const name of names) {
    mod[name] = () => [];
  }
}
const data = require(path.join(npcDir, "npcData"));
// building a definition is slow (the reference does it again for every entry of a pool at every spawn) and gives the same each time
const buildDefinition = data.buildNpcDefinition;
const built = new Map();
data.buildNpcDefinition = (profileID) => {
  if (!built.has(profileID)) {
    built.set(profileID, buildDefinition(profileID));
  }
  return built.get(profileID);
};
const { resolveNpcSpawnPlan } = require(path.join(npcDir, "npcSelection"));
const { npcProfileHasDamageableHull } = require(path.join(npcDir, "npcHullDamageability"));

const profiles = data.listNpcProfiles();
const pools = data.listNpcSpawnPools();

// the numbers a pool roll is given, from a generator of our own, so that the port can be given the same
let seed = 12345;
const sequence = [];
Math.random = () => {
  seed = (seed * 1103515245 + 12345) % 2147483648;
  const value = seed / 2147483648;
  sequence.push(value);
  return value;
};

const queries = new Set(["", "   ", "blood", "guristas", "frigate", "battleship", "rats", "hostiles", "xyz", "angel", "sansha", "!!!", "serpentis anomaly", "concord", "mining", "laser", "pirates", "default", "npc", "Blood Visionary", "BLOOD-VISIONARY"]);
for (const pool of pools) {
  for (const token of [pool.spawnPoolID, pool.name, ...(pool.aliases || [])]) {
    queries.add(token);
  }
}
profiles.forEach((profile, index) => {
  if (index % 19 !== 0) {
    return;
  }
  queries.add(profile.profileID);
  queries.add(profile.name);
  queries.add(String(profile.name || "").toUpperCase());
  if ((profile.aliases || []).length) {
    queries.add(profile.aliases[0]);
  }
  const name = String(profile.name || "");
  if (name.length > 6) {
    queries.add(name.slice(1, name.length - 2));
  }
});

const cases = [];
let n = 0;
for (const query of queries) {
  const amount = (n++ % 4) + 1;
  sequence.length = 0;
  const result = resolveNpcSpawnPlan(query, {
    amount,
    defaultPoolID: "npc_hostiles",
    fallbackProfileID: "generic_hostile",
    entityType: "npc",
    preferPools: true,
    requiredWeaponFamily: "",
  });
  cases.push({
    query,
    amount,
    randoms: [...sequence],
    error: result.success ? null : result.errorMsg,
    suggestions: result.suggestions || [],
    kind: result.success ? result.data.selectionKind : null,
    id: result.success ? result.data.selectionID : null,
    name: result.success ? result.data.selectionName : null,
    profiles: result.success ? result.data.definitions.map((d) => d.profile.profileID) : [],
  });
}
// which ship types have no hit points: the port is told, as it cannot know without the static data
const notDamageable = [...new Set(profiles.map((p) => p.shipTypeID))].filter((id) => !npcProfileHasDamageableHull({ shipTypeID: id, profileID: "" })).sort((a, b) => a - b);
const commit = require("child_process").execSync("git rev-parse HEAD", { cwd: EVEJS }).toString().trim();
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(
  OUT,
  JSON.stringify({ note: "Generated by tools/dev/gen-npc-selection-fixture.js from the reference's resolveNpcSpawnPlan (authored tables only)", referenceCommit: commit, notDamageable, cases }) + "\n",
);
console.log(`${cases.length} queries, ${notDamageable.length} hulls with no hit points -> ${OUT}`);
