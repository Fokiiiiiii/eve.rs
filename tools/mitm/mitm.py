def _text(value):
    if isinstance(value, (bytes, bytearray)):
        return bytes(value).decode("utf-8", "replace")
    return value if isinstance(value, str) else None


def _call_body(payload):
    """(method, args, kwargs) of a CallReq or Notification payload: ((flag, SubStream((1, method, args, kwargs))),)."""
    item = payload[0] if isinstance(payload, (tuple, list)) and len(payload) == 1 else payload
    if isinstance(item, (tuple, list)) and len(item) == 2 and isinstance(item[0], int):
        item = item[1]
    value = item.value if isinstance(item, m.SubStream) else item
    if isinstance(value, tuple) and len(value) >= 3 and _text(value[1]) is not None:
        # A service call begins (1, method, args, kwargs). A call through a remote object begins
        # (substruct((oid, time)), method, args, kwargs); preserve that OID so the journal can
        # associate later bound calls with the service that issued the bind.
        bound_object = value[0] if len(value) > 3 and not (type(value[0]) is int and value[0] in (0, 1)) else None
        return _text(value[1]), value[2], (value[3] if len(value) > 3 else None), bound_object
    return None, None, None, None


def _remote_object_key(value):
    """Find the OID text in a bound object's substruct description."""
    if isinstance(value, dict):
        for item in value.values():
            found = _remote_object_key(item)
            if found:
                return found
    elif isinstance(value, (tuple, list)):
        for item in value:
            found = _remote_object_key(item)
            if found:
                return found
    elif isinstance(value, str) and re.fullmatch(r"N=\d+:\d+", value):
        return value
    return None


def _is_macho_packet(name):
    """The client's packet classes (macho.CallReq) and the reference server's (carbon...machoNetPacket.CallReq)."""
    text = _text(name) or ""
    return text.startswith("macho.") or "machoNetPacket." in text


def _notification_parts(packet):
    """Return the method, arguments, kwargs and any release prefix in a decoded notification body."""
    payload = packet.payload
    if isinstance(payload, (tuple, list)) and len(payload) == 1:
        payload = payload[0]
    if isinstance(payload, (tuple, list)) and len(payload) == 2 and isinstance(payload[0], int):
        payload = payload[1]
    if isinstance(payload, m.SubStream):
        payload = payload.value if payload.raw is None else m.decode(bytes(payload.raw))
    if isinstance(payload, (bytes, bytearray)):
        payload = m.decode(bytes(payload))
    if not isinstance(payload, (tuple, list)):
        return None

    # Ordinary notification streams start with the call marker at index 0; broadcast
    # streams can prefix the call with released object handles. In both forms the
    # method is the string immediately before the argument tuple.
    for index in (1, 2, 0):
        if index + 1 >= len(payload):
            continue
        method = _text(payload[index])
        if method is not None and isinstance(payload[index + 1], (tuple, list, m.List)):
            kwargs = payload[index + 2] if index + 2 < len(payload) else None
            return method, payload[index + 1], kwargs, payload[:index]
    return None


def _notification_record(packet):
    parts = _notification_parts(packet)
    if parts is None:
        event = _notification_event(packet)
        record = {"method": event.get("name"), "args": describe(event.get("args"))}
        if event.get("kwargs") is not None:
            record["kwargs"] = describe(event["kwargs"])
    else:
        method, args, kwargs, prefix = parts
        record = {"method": method, "args": describe(args)}
        if kwargs is not None:
            record["kwargs"] = describe(kwargs)
        if prefix:
            record["prefix"] = describe(prefix)
    if packet.named_payload is not None:
        record["named_payload"] = describe(packet.named_payload)
    return record


def macho_record(pk, encoding):
    """One decoded MachoNet packet as a JSON-serialisable record (no timestamps: see Journal.write)."""
    kind = MACHO_NAMES.get(pk.command, f"type{pk.command}")
    rec = {"stage": "macho", "encoding": encoding, "type": kind}
    rec["service"] = pk.destination.service if pk.destination.service is not None else pk.source.service
    rec["call_id"] = next((c for c in (pk.source.call_id, pk.destination.call_id) if c is not None), None)
    if kind == "Notification":  # the client's decoder: server notifications carry their call in the address, not payload
        rec.update(_notification_record(pk))
    elif kind == "CallReq":
        rec["method"], args, kwargs, bound_object = _call_body(pk.payload)
        rec["args"] = describe(args)
        if kwargs is not None:
            rec["kwargs"] = describe(kwargs)
        if bound_object is not None:
            rec["bound_object"] = describe(bound_object)
    elif kind == "CallRsp":
        rec["result"] = describe(p.result_of(pk))
    elif kind == "ErrorResponse":
        error = p.MachoError.from_packet(pk)
        rec["error"] = {"code": describe(error.code), "payload": describe(error.payload)}
    elif kind.startswith("Ping"):
        pass  # the timings in a ping are per-run
    else:
        rec["payload"] = describe(pk.payload)
    return rec


class Journal:
    """The capture file (one JSON object per line) and, optionally, a readable line per record on stdout."""

    def __init__(self, path, *, echo=None):
        self.file = None
        if path:
            Path(path).parent.mkdir(parents=True, exist_ok=True)
            self.file = open(path, "w", encoding="utf-8")
        self.echo = echo
        self.lock = threading.Lock()
        self.seq = 0
        self.conns = 0
        self.started = time.monotonic()
        self.pending_bound_services = {}
        self.bound_services = {}

    def next_conn(self):
        with self.lock:
            self.conns += 1
            return self.conns

    def write(self, rec):
        with self.lock:
            conn = rec.get("conn")
            if rec.get("stage") == "macho":
                if rec.get("type") == "CallReq":
                    call_key = (conn, rec.get("call_id"), rec.get("dir", "c2s"))
                    service = rec.get("service")
                    method = rec.get("method")
                    bound_key = _remote_object_key(rec.get("bound_object"))
                    if service is None and bound_key is not None:
                        service = self.bound_services.get((conn, bound_key))
                        if service is not None:
                            rec["bound_service"] = service
                    if method == "MachoBindObject" and service:
                        self.pending_bound_services[call_key] = service
                    elif service is not None and rec.get("bound_object") is not None:
                        self.pending_bound_services[call_key] = service
                elif rec.get("type") in ("CallRsp", "ErrorResponse"):
                    reply_direction = rec.get("dir", "s2c")
                    request_direction = "c2s" if reply_direction == "s2c" else "s2c"
                    service = self.pending_bound_services.pop((conn, rec.get("call_id"), request_direction), None)
                    if service is not None and rec.get("type") == "CallRsp":
                        bound_key = _remote_object_key(rec.get("result"))
                        if bound_key is not None:
                            self.bound_services[(conn, bound_key)] = service
            self.seq += 1
            rec = {"seq": self.seq, "t": int((time.monotonic() - self.started) * 1000), **rec}
            if self.file:
                self.file.write(json.dumps(rec, ensure_ascii=False) + "\n")
                self.file.flush()
            if self.echo and self.echo(rec):
                print(render(rec), flush=True)

    def close(self):
        if self.file:
            self.file.close()


class Stream:
    """One direction of one connection: frames the bytes it is shown and records what each frame holds."""

    def __init__(self, direction, conn, journal):
        self.direction, self.conn, self.journal = direction, conn, journal
        self.buffer = bytearray()
        self.dead = False

    def _emit(self, rec):
        self.journal.write({"dir": self.direction, "conn": self.conn, **rec})

    def feed(self, data):
        if self.dead:
            return
        try:
            self.buffer += data
            while not self.dead and len(self.buffer) >= 4:
                (length,) = struct.unpack_from("<I", self.buffer, 0)
                if length > MAX_FRAME:
                    self._emit({"stage": "undecoded", "error": f"frame length {length} exceeds {MAX_FRAME}; this direction is no longer parsed"})
                    self.dead = True
                    return
                if len(self.buffer) < 4 + length:
                    return
                payload = bytes(self.buffer[4 : 4 + length])
                del self.buffer[: 4 + length]
                self._frame(payload)
        except Exception as error:  # the bridge must keep forwarding whatever the analysis does
            self._emit({"stage": "undecoded", "error": f"{type(error).__name__}: {error}"})
            self.dead = True

    def _frame(self, payload):
        encoding = "marshal"
        try:
            if payload[:1] == b"\x78":
                payload = zlib.decompress(payload)
                encoding = "zlib"
            value = m.decode(payload)
        except Exception as error:
            self._emit({"stage": "undecoded", "encoding": encoding, "bytes": len(payload),
                        "error": f"{type(error).__name__}: {error}", "hex": payload[:256].hex()})
            return
        if isinstance(value, m.Object) and _is_macho_packet(value.name):
            try:
                self._emit(macho_record(p.Packet.parse(value), encoding))
                return
            except Exception as error:
                self._emit({"stage": "undecoded", "encoding": encoding, "error": f"macho packet: {error}", "hex": payload[:256].hex()})
                return
        self._emit({"stage": "handshake", "encoding": encoding, "value": describe(value)})


def _pump(src, dst, stream):
    try:
        while True:
            data = src.recv(65536)
            if not data:
                break
            dst.sendall(data)  # forward first: the analysis must not delay or change the bytes
            stream.feed(data)
    except OSError:
        pass
    finally:
        try:
            dst.shutdown(socket.SHUT_WR)
        except OSError:
            pass


def _bridge(client, upstream, journal, conn):
    journal.write({"stage": "event", "conn": conn, "note": f"client connected from {client.getpeername()[0]}"})
    try:
        server = socket.create_connection(upstream, timeout=10)
    except OSError as error:
        journal.write({"stage": "event", "conn": conn, "note": f"upstream {upstream[0]}:{upstream[1]} refused: {error}"})
        client.close()
        return
    server.settimeout(None)
    threads = [
        threading.Thread(target=_pump, args=(client, server, Stream("c2s", conn, journal)), daemon=True),
        threading.Thread(target=_pump, args=(server, client, Stream("s2c", conn, journal)), daemon=True),
    ]
    for thread in threads:
        thread.start()
    for thread in threads:
        thread.join()
    client.close()
    server.close()
    journal.write({"stage": "event", "conn": conn, "note": "closed"})


def _hostport(text):
    host, _, port = text.rpartition(":")
    return (host or "127.0.0.1", int(port))


def _filter(args):
    def keep(rec):
        if args.direction not in (None, "both") and rec.get("dir") != args.direction:
            return False
        if args.service is not None and rec.get("service") != args.service:
            return False
        if args.method is not None and rec.get("method") != args.method:
            return False
        if args.notifications_only and rec.get("type") not in NOTIFICATION_TYPES:
            return False
        return True
    return keep


def _brief(value, limit=220):
    text = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    return text if len(text) <= limit else text[: limit - 3] + "..."


def render(rec):
    """One readable line: C>S / S>C, the packet type, the service and method, the call id, the value."""
    if "dir" not in rec:
        return f"#{rec['seq']} -- {rec.get('note', '')}"
    arrow = "C>S" if rec["dir"] == "c2s" else "S>C"
    stage = rec["stage"]
    if stage == "handshake":
        return f"#{rec['seq']} {arrow} handshake {_brief(rec['value'])}"
    if stage == "undecoded":
        return f"#{rec['seq']} {arrow} UNDECODED {rec.get('bytes', '?')} bytes ({rec['error']}) hex={rec.get('hex', '')}"
    kind, service, call_id = rec["type"], rec.get("service"), rec.get("call_id")
    if kind == "CallReq":
        body = f"{service}.{rec.get('method')} args={_brief(rec.get('args'))}"
    elif kind == "CallRsp":
        body = f"{service} -> {_brief(rec.get('result'))}"
    elif kind == "ErrorResponse":
        body = f"{service} code={_brief(rec['error']['code'])} payload={_brief(rec['error']['payload'])}"
    elif kind == "Notification":
        body = f"{rec.get('method')} args={_brief(rec.get('args'))}"
    elif kind.startswith("Ping"):
        body = ""
    else:
        body = f"{service or ''} {_brief(rec.get('payload'))}"
    return f"#{rec['seq']} {arrow} {kind} call={call_id} {body}".rstrip()


def cmd_capture(args):
    listen, upstream = _hostport(args.listen), _hostport(args.upstream)
    keep = _filter(args)
    journal = Journal(args.out, echo=None if args.quiet else (lambda rec: "dir" not in rec or keep(rec)))
    server = socket.create_server(listen)
    print(f"mitm: {listen[0]}:{listen[1]} -> {upstream[0]}:{upstream[1]}, writing {args.out or 'nothing'}", file=sys.stderr)
    try:
        while True:
            client, _ = server.accept()
            threading.Thread(target=_bridge, args=(client, upstream, journal, journal.next_conn()), daemon=True).start()
    except KeyboardInterrupt:
        pass
    finally:
        server.close()
        journal.close()
    return 0


def cmd_show(args):
    keep = _filter(args)
    with _open_capture(args.capture) as source:
        for line in source:
            rec = json.loads(line)
            if "dir" not in rec or keep(rec):
                print(render(rec))
    return 0


def load(path):
    with _open_capture(path) as source:
        return [json.loads(line) for line in source if line.strip()]


def _core_groups(records, predicate):
    groups = {}
    for rec in records:
        if rec.get("stage") == "macho" and predicate(rec):
            groups.setdefault(rec.get("conn"), []).append(rec)
    for values in groups.values():
        values.sort(key=lambda rec: rec.get("seq", 0))
    return groups


def _core_session_attributes(rec):
    payload = rec.get("payload")
    if not isinstance(payload, dict) or not isinstance(payload.get("$tuple"), list):
        return None
    items = payload["$tuple"]
    if rec.get("type") == "SessionInitialStateNotification":
        return items[2] if len(items) > 2 else None
    if len(items) < 2 or not isinstance(items[1], dict):
        return None
    change = items[1].get("$tuple")
    return change[1] if isinstance(change, list) and len(change) > 1 else None


def _core_mapping_keys(value):
    if isinstance(value, dict) and isinstance(value.get("$dict"), list):
        return sorted(str(pair[0]) for pair in value["$dict"] if isinstance(pair, list) and len(pair) == 2)
    if isinstance(value, dict) and isinstance(value.get("$row"), dict):
        return sorted(value["$row"])
    return None


def _core_mask_session_id(value):
    if isinstance(value, dict) and isinstance(value.get("$tuple"), list) and value["$tuple"]:
        items = list(value["$tuple"])
        items[0] = {"$coreTypeOnly": shape(items[0])}
        return {"$tuple": items}
    return value


def _core_mask_positional_arguments(value, method):
    # Character names and local character/ship IDs differ between isolated live runs. Keep each argument's marshal
    # type and every other positional value in the diff.
    positions = CORE_VOLATILE_ARGUMENTS.get(method, ())
    if positions and isinstance(value, dict) and isinstance(value.get("$tuple"), list):
        items = list(value["$tuple"])
        for index in positions:
            if index < len(items):
                items[index] = {"$coreTypeOnly": shape(items[index])}
        return {"$tuple": items}
    return value


def _core_mask_keyword_arguments(value, method):
    """Mask per-run module IDs in Undock's client-supplied flag-to-module map."""
    if method != "Undock" or not isinstance(value, dict) or not isinstance(value.get("$dict"), list):
        return value
    pairs = []
    for pair in value["$dict"]:
        if isinstance(pair, list) and len(pair) == 2 and pair[0] == "onlineModules":
            modules = pair[1]
            if isinstance(modules, dict) and isinstance(modules.get("$dict"), list):
                masked = []
                for module in modules["$dict"]:
                    if isinstance(module, list) and len(module) == 2:
                        module_id = module[1]
                        # Shapes have already been checked before this helper is used.
                        module_id = {"$coreVolatileLong": True} if isinstance(module_id, dict) and "$long" in module_id else module_id
                        masked.append([module[0], module_id])
                    else:
                        masked.append(module)
                pair = [pair[0], {"$dict": masked}]
        pairs.append(pair)
    return {"$dict": pairs}


def _core_value_difference(reference, candidate, *, method=None, shape_only=False,
                           strict_volatile=False, session_payload=False, id_result=False):
    reference_shape, candidate_shape = shape(reference), shape(candidate)
    if reference_shape != candidate_shape:
        return {"kind": "shape", "differences": differences(reference_shape, candidate_shape)}
    if shape_only or (method in VOLATILE_METHODS and not strict_volatile):
        return None
    if id_result and method in (CORE_VOLATILE_ID_RESULT_METHODS | CORE_VOLATILE_RESULT_METHODS) and not strict_volatile:
        return None
    if session_payload and not strict_volatile:
        reference = _core_mask_session_id(reference)
        candidate = _core_mask_session_id(candidate)
    volatile = frozenset() if strict_volatile else CORE_VOLATILE_KEYS
    found = differences(reference, candidate, volatile_keys=volatile)
    return {"kind": "value", "differences": found} if found else None


def _core_reply_view(replies):
    if not replies:
        return {"presence": "missing", "count": 0}
    result = {"presence": "present", "count": len(replies), "replies": []}
    for rec in replies:
        kind = rec.get("type")
        item = {"kind": kind}
        if kind == "CallRsp":
            item["shape"] = shape(rec.get("result"))
        elif kind == "ErrorResponse":
            item["shape"] = shape(_core_error_value(rec.get("error")))
            item["error"] = rec.get("error")
        result["replies"].append(item)
    return result


def _core_error_value(error):
    error = error if isinstance(error, dict) else {}
    return {"$dict": [["code", error.get("code")], ["payload", error.get("payload")]]}


def _core_request_signature(rec, ignore_volatile):
    if rec is None:
        return None
    service = _normal_service(rec.get("service") or rec.get("bound_service"), ignore_volatile)
    method = rec.get("method")
    return {
        "service": service,
        "method": method,
        "args_shape": shape(rec.get("args")),
        "kwargs_shape": shape(rec.get("kwargs")),
    }


def _core_align(left, right, signature, *, prefer_index_on_permutation=False):
    """Align two ordered streams by their stable call or notification identity.

    Insertions and removals stay local to their position instead of shifting every later result. When the same
    identities occur in a different order, pair by position so the report identifies the reordered names.
    """
    left_keys = [signature(record) for record in left]
    right_keys = [signature(record) for record in right]
    if (
        prefer_index_on_permutation
        and len(left_keys) == len(right_keys)
        and Counter(left_keys) == Counter(right_keys)
    ):
        return list(zip(left, right))

    aligned = []
    matcher = SequenceMatcher(None, left_keys, right_keys, autojunk=False)
    for tag, i1, i2, j1, j2 in matcher.get_opcodes():
        if tag == "equal":
            aligned.extend(zip(left[i1:i2], right[j1:j2]))
        elif tag == "replace":
            paired = min(i2 - i1, j2 - j1)
            aligned.extend(zip(left[i1:i1 + paired], right[j1:j1 + paired]))
            aligned.extend((record, None) for record in left[i1 + paired:i2])
            aligned.extend((None, record) for record in right[j1 + paired:j2])
        elif tag == "delete":
            aligned.extend((record, None) for record in left[i1:i2])
        elif tag == "insert":
            aligned.extend((None, record) for record in right[j1:j2])
    return aligned


def _core_pair_connections(left_groups, right_groups, signature):
    """Pair client connections by their ordered RPC identities, not by proxy-local connection numbers.

    A test harness can make an extra login connection on one side (for example, to seed account roles). Pair exact
    streams first, then streams with at least two shared calls. If the remaining connection counts are equal, pair
    them in capture order so a one-call method change is reported as a call difference instead of two omissions.
    """
    left = {conn: [signature(record) for record in records] for conn, records in left_groups.items()}
    right = {conn: [signature(record) for record in records] for conn, records in right_groups.items()}
    left_order = list(left)
    right_order = list(right)
    pairs = []

    def pair_exact():
        for left_conn in list(left_order):
            key = tuple(left[left_conn])
            right_conn = next((conn for conn in right_order if tuple(right[conn]) == key), None)
            if right_conn is None:
                continue
            pairs.append((left_conn, right_conn))
            left_order.remove(left_conn)
            right_order.remove(right_conn)

    pair_exact()

    candidates = []
    for left_index, left_conn in enumerate(left_order):
        for right_index, right_conn in enumerate(right_order):
            matcher = SequenceMatcher(None, left[left_conn], right[right_conn], autojunk=False)
            common = sum(block.size for block in matcher.get_matching_blocks())
            if common >= 2:
                candidates.append((common, matcher.ratio(), -left_index, -right_index, left_conn, right_conn))
    used_left, used_right = set(), set()
    for _, _, _, _, left_conn, right_conn in sorted(candidates, reverse=True):
        if left_conn in used_left or right_conn in used_right:
            continue
        pairs.append((left_conn, right_conn))
        used_left.add(left_conn)
        used_right.add(right_conn)
    left_order = [conn for conn in left_order if conn not in used_left]
    right_order = [conn for conn in right_order if conn not in used_right]

    if len(left_order) == len(right_order):
        pairs.extend(zip(left_order, right_order))
        left_order.clear()
        right_order.clear()
    pairs.extend((conn, None) for conn in left_order)
    pairs.extend((None, conn) for conn in right_order)
    return pairs


def _core_connection_pairs_with_remaining(pairs, left_groups, right_groups, signature):
    used_left = {left for left, _ in pairs if left is not None}
    used_right = {right for _, right in pairs if right is not None}
    left = {conn: records for conn, records in left_groups.items() if conn not in used_left}
    right = {conn: records for conn, records in right_groups.items() if conn not in used_right}
    pairs.extend(_core_pair_connections(left, right, signature))
    return pairs


def _core_compare_calls(reference, candidate, strict_volatile):
    is_call = lambda rec: rec.get("type") == "CallReq"
    is_reply = lambda rec: rec.get("type") in ("CallRsp", "ErrorResponse")
    ref_calls, cand_calls = _core_groups(reference, is_call), _core_groups(candidate, is_call)
    ref_replies, cand_replies = _core_groups(reference, is_reply), _core_groups(candidate, is_reply)
    rows, differences_found, orphan_replies = [], [], []

    def reply_map(records, calls):
        known = {(conn, rec.get("call_id")) for conn, items in calls.items() for rec in items}
        mapped = {}
        for conn, items in records.items():
            for rec in items:
                key = (conn, rec.get("call_id"))
                mapped.setdefault(key, []).append(rec)
                if key not in known:
                    orphan_replies.append({"side": "reference" if records is ref_replies else "candidate",
                                           "conn": conn, "seq": rec.get("seq"), "type": rec.get("type"),
                                           "call_id": rec.get("call_id")})
        return mapped

    ref_by_call = reply_map(ref_replies, ref_calls)
    cand_by_call = reply_map(cand_replies, cand_calls)
    # A missing bound_service is a capture limitation, not proof that two otherwise matching calls
    # target different services. Align on the method and argument shapes, then report a service
    # difference only when both sides actually identify one below.
    signature = lambda record: (
        record.get("method"),
        json.dumps(shape(record.get("args")), sort_keys=True),
        json.dumps(shape(record.get("kwargs")), sort_keys=True),
    )
    connection_pairs = _core_pair_connections(ref_calls, cand_calls, signature)
    for ref_conn, cand_conn in connection_pairs:
        left, right = ref_calls.get(ref_conn, []), cand_calls.get(cand_conn, [])
        for ordinal, (ref, cand) in enumerate(_core_align(left, right, signature)):
            ref_signature = _core_request_signature(ref, not strict_volatile)
            cand_signature = _core_request_signature(cand, not strict_volatile)
            issues = []
            method = ref.get("method") if ref else (cand.get("method") if cand else None)
            if ref is None or cand is None:
                issues.append({"kind": "call_presence", "reference": ref_signature, "candidate": cand_signature})
            else:
                services_differ = (
                    ref_signature["service"] is not None
                    and cand_signature["service"] is not None
                    and ref_signature["service"] != cand_signature["service"]
                )
                if ref_signature["method"] != cand_signature["method"] or services_differ:
                    issues.append({"kind": "call_order", "reference": ref_signature, "candidate": cand_signature})
                for field in ("args", "kwargs"):
                    reference_value = ref.get(field)
                    candidate_value = cand.get(field)
                    if field == "args" and not strict_volatile and shape(reference_value) == shape(candidate_value):
                        reference_value = _core_mask_positional_arguments(reference_value, method)
                        candidate_value = _core_mask_positional_arguments(candidate_value, method)
                    elif field == "kwargs" and not strict_volatile and shape(reference_value) == shape(candidate_value):
                        reference_value = _core_mask_keyword_arguments(reference_value, method)
                        candidate_value = _core_mask_keyword_arguments(candidate_value, method)
                    difference = _core_value_difference(
                        reference_value, candidate_value, method=method, strict_volatile=strict_volatile,
                    )
                    if difference:
                        issues.append({**difference, "kind": f"request_{field}_{difference['kind']}"})

            ref_responses = ref_by_call.get((ref_conn, ref.get("call_id")), []) if ref else []
            cand_responses = cand_by_call.get((cand_conn, cand.get("call_id")), []) if cand else []
            ref_reply, cand_reply = _core_reply_view(ref_responses), _core_reply_view(cand_responses)
            if ref_reply["presence"] != cand_reply["presence"] or ref_reply["count"] != cand_reply["count"]:
                issues.append({"kind": "reply_presence", "reference": ref_reply, "candidate": cand_reply})
            elif ref_responses and cand_responses:
                if len(ref_responses) != 1:
                    issues.append({"kind": "reply_count", "reference": ref_reply, "candidate": cand_reply})
                for reply_index, (ref_response, cand_response) in enumerate(zip(ref_responses, cand_responses)):
                    if ref_response.get("type") != cand_response.get("type"):
                        issues.append({"kind": "reply_kind", "reply_index": reply_index,
                                       "reference": ref_response.get("type"), "candidate": cand_response.get("type")})
                    elif ref_response.get("type") == "CallRsp":
                        difference = _core_value_difference(
                            ref_response.get("result"), cand_response.get("result"), method=method,
                            strict_volatile=strict_volatile, id_result=True,
                        )
                        if difference:
                            issues.append({**difference, "kind": f"reply_{difference['kind']}", "reply_index": reply_index})
                    else:
                        difference = _core_value_difference(
                            _core_error_value(ref_response.get("error")), _core_error_value(cand_response.get("error")), method=method,
                            strict_volatile=strict_volatile,
                        )
                        if difference:
                            issues.append({**difference, "kind": f"error_{difference['kind']}", "reply_index": reply_index})

            row = {
                "conn": ref_conn if ref_conn is not None else cand_conn,
                "reference_conn": ref_conn,
                "candidate_conn": cand_conn,
                "ordinal": ordinal,
                "reference": ref_signature,
                "candidate": cand_signature,
                "reply": {"reference": ref_reply, "candidate": cand_reply},
                "issues": issues,
            }
            rows.append(row)
            if issues:
                differences_found.append(row)
    return rows, differences_found, orphan_replies, connection_pairs


def _core_compare_notifications(reference, candidate, strict_volatile, connection_pairs):
    wanted = lambda rec: rec.get("type") == "Notification" or rec.get("type") in SESSION_TYPES
    ref_groups, cand_groups = _core_groups(reference, wanted), _core_groups(candidate, wanted)
    rows, differences_found, session_rows = [], [], []
    connection_pairs = _core_connection_pairs_with_remaining(
        list(connection_pairs), ref_groups, cand_groups,
        lambda record: (record.get("type"), record.get("service"), record.get("method")),
    )
    for ref_conn, cand_conn in connection_pairs:
        left, right = ref_groups.get(ref_conn, []), cand_groups.get(cand_conn, [])
        def signature(record):
            if record.get("type") == "Notification":
                return (
                    record.get("type"),
                    _normal_service(record.get("service"), not strict_volatile),
                    record.get("method"),
                )
            return (record.get("type"),)

        for ordinal, (ref, cand) in enumerate(_core_align(
            left, right, signature, prefer_index_on_permutation=True,
        )):
            ref_name = (ref.get("type"), _normal_service(ref.get("service"), not strict_volatile), ref.get("method")) if ref else None
            cand_name = (cand.get("type"), _normal_service(cand.get("service"), not strict_volatile), cand.get("method")) if cand else None
            issues = []
            if ref is None or cand is None:
                issues.append({"kind": "notification_presence", "reference": ref_name, "candidate": cand_name})
            elif ref_name != cand_name:
                issues.append({"kind": "notification_order_or_name", "reference": ref_name, "candidate": cand_name})
            elif ref.get("type") == "Notification":
                for field in ("args", "kwargs"):
                    difference = _core_value_difference(
                        ref.get(field), cand.get(field), strict_volatile=strict_volatile,
                    )
                    if difference:
                        issues.append({**difference, "kind": f"notification_{field}_{difference['kind']}"})
            else:
                difference = _core_value_difference(
                    ref.get("payload"), cand.get("payload"), strict_volatile=strict_volatile, session_payload=True,
                ) if ref and cand else None
                if difference:
                    issues.append({**difference, "kind": f"session_{difference['kind']}"})

            ref_attrs = _core_session_attributes(ref) if ref and ref.get("type") in SESSION_TYPES else None
            cand_attrs = _core_session_attributes(cand) if cand and cand.get("type") in SESSION_TYPES else None
            session = None
            if ref_attrs is not None or cand_attrs is not None:
                attr_difference = _core_value_difference(ref_attrs, cand_attrs, strict_volatile=strict_volatile)
                session = {
                    "reference_attribute_keys": _core_mapping_keys(ref_attrs),
                    "candidate_attribute_keys": _core_mapping_keys(cand_attrs),
                    "attribute_difference": attr_difference,
                }
                session_rows.append({
                    "conn": ref_conn if ref_conn is not None else cand_conn,
                    "reference_conn": ref_conn,
                    "candidate_conn": cand_conn,
                    "ordinal": ordinal,
                    "event": ref_name or cand_name,
                    **session,
                })
                if attr_difference and not any(issue.get("kind") == f"session_{attr_difference['kind']}" for issue in issues):
                    issues.append({**attr_difference, "kind": f"session_attributes_{attr_difference['kind']}"})

            row = {"conn": ref_conn if ref_conn is not None else cand_conn,
                   "reference_conn": ref_conn, "candidate_conn": cand_conn,
                   "ordinal": ordinal, "reference": ref_name, "candidate": cand_name,
                   "session_attributes": session, "issues": issues}
            rows.append(row)
            if issues:
                differences_found.append(row)
    return rows, differences_found, session_rows


def _core_compare_handshakes(reference, candidate, strict_volatile, connection_pairs):
    def groups(records):
        result = {}
        for rec in records:
            if rec.get("stage") == "handshake":
                result.setdefault((rec.get("conn"), rec.get("dir")), []).append(rec)
        for values in result.values():
            values.sort(key=lambda rec: rec.get("seq", 0))
        return result

    ref_groups, cand_groups = groups(reference), groups(candidate)
    rows, differences_found = [], []
    ref_by_conn, cand_by_conn = {}, {}
    for (conn, direction), values in ref_groups.items():
        ref_by_conn.setdefault(conn, []).extend(values)
    for (conn, direction), values in cand_groups.items():
        cand_by_conn.setdefault(conn, []).extend(values)
    connection_pairs = _core_connection_pairs_with_remaining(
        list(connection_pairs), ref_by_conn, cand_by_conn,
        lambda record: (record.get("dir"), shape(record.get("value"))),
    )
    for ref_conn, cand_conn in connection_pairs:
        directions = sorted({direction for conn, direction in set(ref_groups) | set(cand_groups)
                             if conn in (ref_conn, cand_conn)})
        for direction in directions:
            left = ref_groups.get((ref_conn, direction), []) if ref_conn is not None else []
            right = cand_groups.get((cand_conn, direction), []) if cand_conn is not None else []
            for ordinal in range(max(len(left), len(right))):
                ref = left[ordinal] if ordinal < len(left) else None
                cand = right[ordinal] if ordinal < len(right) else None
                issues = []
                if ref is None or cand is None:
                    issues.append({"kind": "handshake_presence", "reference": ref is not None, "candidate": cand is not None})
                else:
                    difference = _core_value_difference(
                        ref.get("value"), cand.get("value"), shape_only=direction == "c2s" and not strict_volatile,
                        strict_volatile=strict_volatile,
                    )
                    if difference:
                        issues.append({**difference, "kind": f"handshake_{difference['kind']}"})
                row = {
                    "conn": ref_conn if ref_conn is not None else cand_conn,
                    "reference_conn": ref_conn,
                    "candidate_conn": cand_conn,
                    "direction": direction,
                    "ordinal": ordinal,
                    "issues": issues,
                }
                rows.append(row)
                if issues:
                    differences_found.append(row)
    return rows, differences_found


def diff_core(reference, candidate, *, strict_volatile=False):
    """Compare every core-flow request/reply, handshake frame, and ordered server notice in two captures."""
    calls, call_differences, orphan_replies, connection_pairs = _core_compare_calls(
        reference, candidate, strict_volatile,
    )
    notices, notification_differences, session_changes = _core_compare_notifications(
        reference, candidate, strict_volatile, connection_pairs,
    )
    handshakes, handshake_differences = _core_compare_handshakes(
        reference, candidate, strict_volatile, connection_pairs,
    )
    ref_undecoded = [rec for rec in reference if rec.get("stage") == "undecoded"]
    cand_undecoded = [rec for rec in candidate if rec.get("stage") == "undecoded"]
    undecoded = {"reference": len(ref_undecoded), "candidate": len(cand_undecoded)}
    undecoded_differences = []
    if ref_undecoded or cand_undecoded:
        undecoded_differences = [
            {"reference": [rec.get("error") for rec in ref_undecoded],
             "candidate": [rec.get("error") for rec in cand_undecoded]}
        ]
    unanswered = [row for row in calls if
                  (row["reference"] is not None and row["reply"]["reference"]["presence"] == "missing")
                  or (row["candidate"] is not None and row["reply"]["candidate"]["presence"] == "missing")]
    reply_presence_differences = sum(
        1 for row in calls
        if row["reply"]["reference"]["presence"] != row["reply"]["candidate"]["presence"]
        or row["reply"]["reference"].get("count", 0) != row["reply"]["candidate"].get("count", 0)
    )
    summary = {
        "reference_calls": sum(1 for rec in reference if rec.get("type") == "CallReq"),
        "candidate_calls": sum(1 for rec in candidate if rec.get("type") == "CallReq"),
        "compared_calls": len(calls),
        "call_differences": len(call_differences),
        "unanswered_calls": len(unanswered),
        "reply_presence_differences": reply_presence_differences,
        "reference_notifications": sum(1 for rec in reference if rec.get("type") == "Notification" or rec.get("type") in SESSION_TYPES),
        "candidate_notifications": sum(1 for rec in candidate if rec.get("type") == "Notification" or rec.get("type") in SESSION_TYPES),
        "notification_differences": len(notification_differences),
        "session_changes": len(session_changes),
        "handshake_differences": len(handshake_differences),
        "orphan_replies": len(orphan_replies),
        "undecoded": undecoded,
    }
    different = bool(call_differences or notification_differences or handshake_differences or orphan_replies or undecoded_differences)
    return {
        "identical": not different,
        "volatile_values_ignored": not strict_volatile,
        "summary": summary,
        "calls": calls,
        "call_differences": call_differences,
        "notifications": notices,
        "notification_differences": notification_differences,
        "session_changes": session_changes,
        "handshakes": handshakes,
        "handshake_differences": handshake_differences,
        "orphan_replies": orphan_replies,
        "undecoded_differences": undecoded_differences,
    }


# Option C of the differential gate: the same flow is recorded twice on each server. A leaf whose value changes
# between the two runs of one server is nondeterministic (ids, timestamps, random numbers); it becomes a wildcard
# for both servers and is compared by marshal type only. Every other leaf must match exactly.
RUN_SKIPPED_FIELDS = frozenset({"seq", "dir", "conn", "stage", "encoding", "call_id"})


def _run_index(records):
    """Map each MachoNet record to a run-independent identity.

    The identity is the connection's order of first appearance, the record type, service, method and occurrence.
    A reply takes the identity of the request it answers (connection and call id), so call ids that are drawn
    afresh in every run still line up. Records without a request are kept as orphans.
    """
    ordinals, requests, counts, index = {}, {}, Counter(), {}
    for rec in sorted((r for r in records if r.get("stage") == "macho"), key=lambda r: r.get("seq", 0)):
        conn = rec.get("conn")
        ordinal = ordinals.setdefault(conn, len(ordinals) + 1)
        kind = rec.get("type")
        if kind in ("CallRsp", "ErrorResponse"):
            base = requests.get((conn, rec.get("call_id")))
            head = ("reply", base) if base is not None else ("orphan", ordinal, kind, rec.get("call_id"))
        else:
            head = (ordinal, kind, rec.get("service"), rec.get("method"))
        counts[head] += 1
        key = (*head, counts[head])
        if kind == "CallReq":
            requests[(conn, rec.get("call_id"))] = key
        index[key] = rec
    return index


def _run_label(key):
    if key[0] == "reply":
        return f"reply[{_run_label(key[1])}]#{key[2]}"
    if key[0] == "orphan":
        return f"orphan[conn{key[1]} {key[2]} call{key[3]}]#{key[4]}"
    ordinal, kind, service, method, occurrence = key
    return f"conn{ordinal} {kind} {service}.{method}#{occurrence}"


def _run_leaves(value, path=""):
    """Yield (path, (marshal type, value)) for every scalar. Dictionary order is not part of the path."""
    if isinstance(value, dict):
        for name in value:
            yield from _run_leaves(value[name], f"{path}/{name}")
    elif isinstance(value, list):
        for position, item in enumerate(value):
            yield from _run_leaves(item, f"{path}/{position}")
    else:
        yield path, (type(value).__name__, value)


def _run_snapshot(records):
    index = _run_index(records)
    return {
        key: dict(_run_leaves({name: rec[name] for name in rec if name not in RUN_SKIPPED_FIELDS}))
        for key, rec in index.items()
    }


def _run_show(leaf):
    return None if leaf is None else [leaf[0], leaf[1]]


def _run_compare(reference_first, reference_second, candidate_first, candidate_second):
    snapshots = (reference_first, reference_second, candidate_first, candidate_second)
    differences, unstable, wildcards = [], [], []
    summary = {"reference_records": len(reference_first), "candidate_records": len(candidate_first),
               "compared_records": 0, "compared_values": 0}
    for key in sorted(set().union(*snapshots), key=_run_label):
        label = _run_label(key)
        present = [key in snap for snap in snapshots]
        if present[0] != present[1]:
            unstable.append({"side": "reference", "record": label})
        if present[2] != present[3]:
            unstable.append({"side": "candidate", "record": label})
        if present[0] != present[1] or present[2] != present[3]:
            continue
        if present[0] and not present[2]:
            differences.append({"record": label, "kind": "missing_record"})
            continue
        if present[2] and not present[0]:
            differences.append({"record": label, "kind": "extra_record"})
            continue
        if not present[0]:
            continue
        summary["compared_records"] += 1
        leaves = [snap[key] for snap in snapshots]
        paths = set().union(*leaves)
        # A wildcard varies between the two runs of one server. Comparing the servers with each other never makes one.
        varying = {
            path for path in paths
            if len({leaves[0].get(path), leaves[1].get(path)}) > 1
            or len({leaves[2].get(path), leaves[3].get(path)}) > 1
        }
        for path in sorted(varying):
            wildcards.append({"record": label, "path": path})
        for path in sorted(paths):
            left, right = leaves[0].get(path), leaves[2].get(path)
            if path in varying:
                if left is not None and right is not None:
                    if left[0] == right[0]:
                        continue
                    kind = "wildcard_type"
                elif (left is None) != (right is None):
                    kind = "wildcard_presence"
                else:
                    continue
            else:
                summary["compared_values"] += 1
                if left == right:
                    continue
                kind = "value" if left is not None and right is not None else ("missing" if right is None else "extra")
            differences.append({"record": label, "path": path, "kind": kind,
                                "reference": _run_show(left), "candidate": _run_show(right)})
    summary.update({"differences": len(differences), "unstable_records": len(unstable), "wildcards": len(wildcards)})
    return {
        "identical": not differences and not unstable,
        "summary": summary,
        "differences": differences,
        "unstable_records": unstable,
        "wildcards": wildcards,
    }


def diff_runs(reference_first, reference_second, candidate_first, candidate_second):
    """Compare one flow recorded twice on each server, treating values that vary within a server as wildcards."""
    return _run_compare(
        _run_snapshot(reference_first), _run_snapshot(reference_second),
        _run_snapshot(candidate_first), _run_snapshot(candidate_second),
    )


def _open_capture(path):
    return gzip.open(path, "rt", encoding="utf-8") if str(path).endswith(".gz") else open(path, encoding="utf-8")


def _normal_service(name, ignore_volatile):
    return re.sub(r"OID[+-]\d+", "OID", name) if (ignore_volatile and name) else name


def _sort_dicts(value):
    """The same value with every marshal dictionary's pairs sorted by key (the client reads a dictionary by key)."""
    if isinstance(value, dict):
        if isinstance(value.get("$dict"), list):
            pairs = [[k, _sort_dicts(v)] for k, v in value["$dict"]]
            return {"$dict": sorted(pairs, key=lambda pair: json.dumps(pair[0], sort_keys=True))}
        return {k: _sort_dicts(v) for k, v in value.items()}
    if isinstance(value, list):
        return [_sort_dicts(v) for v in value]
    return value


def _is_notification(category):
    return category == "notification" or (isinstance(category, str) and category.endswith("Notification"))


def events(records, ignore_volatile, ignore_key_order=False, ignore_notification_order=False):
    """Two streams, each in capture order: the calls the client made, and what the server sent.

    The two directions are not interleaved: a server notification can race the client's first call on a new
    connection, and that order depends on timing. Results and errors take the service and method of their call."""
    calls = {}
    for rec in records:
        if rec.get("stage") == "macho" and rec["type"] == "CallReq":
            calls[(rec.get("conn"), rec.get("call_id"))] = (rec.get("service"), rec.get("method"))
    client, server = [], []
    for rec in records:
        if rec.get("stage") != "macho" or rec["type"].startswith("Ping"):
            continue
        kind, key = rec["type"], (rec.get("conn"), rec.get("call_id"))
        if kind == "CallReq":
            client.append(("call", _normal_service(rec.get("service"), ignore_volatile), rec.get("method"), rec.get("args")))
        elif kind in ("CallRsp", "ErrorResponse"):
            service, method = calls.get(key, (rec.get("service"), None))
            value = rec.get("result") if kind == "CallRsp" else rec.get("error")
            if ignore_volatile and method in VOLATILE_METHODS and kind == "CallRsp":
                value = shape(value)
            category = "result" if kind == "CallRsp" else "error"
            server.append((category, _normal_service(service, ignore_volatile), method, value))
        elif kind == "Notification":
            server.append(("notification", _normal_service(rec.get("service"), ignore_volatile), rec.get("method"), rec.get("args")))
        else:
            value = rec.get("payload")
            if ignore_volatile and kind in SESSION_TYPES and isinstance(value, dict) and value.get("$tuple"):
                # the payload leads with the session id: (sessionID, changeKind, changes)
                value = {"$tuple": [shape(value["$tuple"][0]), *value["$tuple"][1:]]}
            server.append((kind, None, None, value))
    if ignore_key_order:
        client = [(c, s, m, _sort_dicts(v)) for c, s, m, v in client]
        server = [(c, s, m, _sort_dicts(v)) for c, s, m, v in server]
    if ignore_notification_order:
        # the notices are compared as a set, after the results: independent notices may arrive in any order
        notices = [e for e in server if _is_notification(e[0])]
        server = [e for e in server if not _is_notification(e[0])]
        server += sorted(notices, key=lambda e: json.dumps(list(e), sort_keys=True, default=str))
    return client, server


def _first_divergence(reference, candidate, ignore_volatile):
    """The first divergence of two event lists, or None: call order, then shape, then values."""
    volatile = VOLATILE_KEYS if ignore_volatile else frozenset()
    for index, (a, b) in enumerate(zip(reference, candidate)):
        if a[:3] != b[:3]:
            return index, "call order", [f"reference {a[:3]}", f"candidate {b[:3]}"]
        if shape(a[3]) != shape(b[3]):
            return index, f"{a[0]} shape", differences(shape(a[3]), shape(b[3]))[:10]
        found = differences(a[3], b[3], volatile_keys=volatile)
        if found:
            return index, f"{a[0]} value", found[:10]
    if len(reference) != len(candidate):
        longer = "reference" if len(reference) > len(candidate) else "candidate"
        extra = abs(len(reference) - len(candidate))
        return min(len(reference), len(candidate)), "length", [f"{longer} has {extra} more events"]
    return None


def compare(reference, candidate, ignore_volatile):
    """The first divergence in the client's calls, else in the server's events: (stream, index, kind, details, a, b)."""
    for stream, a, b in (("client calls", reference[0], candidate[0]), ("server events", reference[1], candidate[1])):
        found = _first_divergence(a, b, ignore_volatile)
        if found:
            index, kind, details = found
            at_a = a[index] if index < len(a) else None
            at_b = b[index] if index < len(b) else None
            return stream, index, kind, details, at_a, at_b, max(len(a), len(b))
    return None


def _canonical_shape(value, ignore_key_order):
    return shape(_sort_dicts(value) if ignore_key_order else value)


def _string_leaves(value):
    """Strings carried by an ErrorResponse, including localized text and reason names."""
    if isinstance(value, str):
        return [] if value.startswith("$bytes:") else [value]
    if isinstance(value, list):
        return [leaf for item in value for leaf in _string_leaves(item)]
    if isinstance(value, dict):
        if "$buffer" in value or "$pickle" in value:
            return []
        return [leaf for item in value.values() for leaf in _string_leaves(item)]
    return []


def _named_value(value, key):
    if isinstance(value, dict):
        pairs = value.get("$dict")
        if isinstance(pairs, list):
            for pair in pairs:
                if isinstance(pair, list) and len(pair) == 2 and pair[0] == key:
                    return pair[1]
                if isinstance(pair, list) and len(pair) == 2:
                    found = _named_value(pair[1], key)
                    if found is not None:
                        return found
        for child in value.values():
            found = _named_value(child, key)
            if found is not None:
                return found
    elif isinstance(value, list):
        for child in value:
            found = _named_value(child, key)
            if found is not None:
                return found
    return None


def _connection_groups(records):
    first_seq, usernames, groups = {}, {}, defaultdict(list)
    for record in records:
        conn = record.get("conn")
        first_seq[conn] = min(first_seq.get(conn, record.get("seq", 0)), record.get("seq", 0))
        groups[conn].append(record)
        if record.get("stage") == "handshake" and record.get("dir") == "c2s":
            name = _named_value(record.get("value"), "user_name")
            if isinstance(name, str) and name:
                usernames[conn] = re.sub(r"-[0-9a-f]{8,}$", "-*", name, flags=re.IGNORECASE)
    return first_seq, usernames, groups


def _connection_signatures(records):
    return [(_normal_service(record.get("service"), True), record.get("method"))
            for record in records if record.get("stage") == "macho" and record.get("type") == "CallReq"]


def _comparison_connections(reference_records, candidate_records):
    """Pair same-account sockets by call sequence so setup logins do not shift the actual scenario."""
    ref_first, ref_names, ref_groups = _connection_groups(reference_records)
    got_first, got_names, got_groups = _connection_groups(candidate_records)
    ref_aliases, got_aliases = {}, {}
    names = set(ref_names.values()) | set(got_names.values())
    for conn, first in ref_first.items():
        if conn not in ref_names:
            names.add(f"conn-{conn}")
    for conn, first in got_first.items():
        if conn not in got_names:
            names.add(f"conn-{conn}")

    for name in names:
        ref_conns = sorted((conn for conn in ref_first if ref_names.get(conn, f"conn-{conn}") == name),
                           key=lambda conn: ref_first[conn])
        got_conns = sorted((conn for conn in got_first if got_names.get(conn, f"conn-{conn}") == name),
                           key=lambda conn: got_first[conn])
        scores = []
        for ri, ref_conn in enumerate(ref_conns):
            left = _connection_signatures(ref_groups[ref_conn])
            for gi, got_conn in enumerate(got_conns):
                right = _connection_signatures(got_groups[got_conn])
                matcher = SequenceMatcher(None, left, right, autojunk=False)
                common = sum(block.size for block in matcher.get_matching_blocks())
                score = (common, matcher.ratio(), -abs(len(left) - len(right)))
                scores.append((score, ri, gi))
        matched_ref, matched_got, pairs = set(), set(), []
        for score, ri, gi in sorted(scores, key=lambda item: (item[0], -item[1], -item[2]), reverse=True):
            if ri in matched_ref or gi in matched_got or score[0] == 0 and score[1] == 0:
                continue
            matched_ref.add(ri)
            matched_got.add(gi)
            pairs.append((ri, gi))

        ordinal = 0
        for ri, gi in sorted(pairs):
            ordinal += 1
            alias = (name, ordinal)
            ref_aliases[ref_conns[ri]] = alias
            got_aliases[got_conns[gi]] = alias
        for ri, conn in enumerate(ref_conns):
            if ri not in matched_ref:
                ordinal += 1
                ref_aliases[conn] = (f"{name} [reference-only]", ordinal)
        for gi, conn in enumerate(got_conns):
            if gi not in matched_got:
                ordinal += 1
                got_aliases[conn] = (f"{name} [candidate-only]", ordinal)

    ref = [{**record, "_compare_conn": ref_aliases.get(record.get("conn"), (f"conn-{record.get('conn')}", 1))}
           for record in reference_records]
    got = [{**record, "_compare_conn": got_aliases.get(record.get("conn"), (f"conn-{record.get('conn')}", 1))}
           for record in candidate_records]
    return ref, got


def _connection_label(conn):
    if isinstance(conn, tuple) and len(conn) == 2:
        name, index = conn
        if name.startswith("conn-"):
            return f"conn={name[5:]}"
        return f"user={name} connection#{index}"
    return f"conn={conn}"


def _capture_calls(records):
    calls = defaultdict(list)
    replies = defaultdict(list)
    for rec in records:
        if rec.get("stage") != "macho":
            continue
        conn = rec.get("_compare_conn", rec.get("conn"))
        key = (conn, rec.get("call_id"))
        if rec.get("type") == "CallReq":
            calls[conn].append(rec)
        elif rec.get("type") in ("CallRsp", "ErrorResponse"):
            replies[key].append(rec)
    for conn in calls:
        calls[conn].sort(key=lambda rec: rec.get("seq", 0))
    return calls, replies


def _call_signature(record, ignore_volatile):
    return (_normal_service(record.get("service"), ignore_volatile), record.get("method"))


def _reply_summary(reply):
    if reply is None:
        return "missing"
    return reply.get("type", "unknown")


def _compare_call_reply(ref_reply, got_reply, *, ignore_key_order, label, issues):
    if ref_reply is None or got_reply is None:
        if (ref_reply is None) != (got_reply is None):
            issues.append(f"{label}: reply presence differs (reference={_reply_summary(ref_reply)}, candidate={_reply_summary(got_reply)})")
        return
    if ref_reply.get("type") != got_reply.get("type"):
        issues.append(f"{label}: reply kind differs (reference={_reply_summary(ref_reply)}, candidate={_reply_summary(got_reply)})")
        return
    if ref_reply["type"] == "CallRsp":
        ref_result, got_result = ref_reply.get("result"), got_reply.get("result")
        if _canonical_shape(ref_result, ignore_key_order) != _canonical_shape(got_result, ignore_key_order):
            delta = differences(_canonical_shape(ref_result, ignore_key_order), _canonical_shape(got_result, ignore_key_order))
            issues.append(f"{label}: reply marshal shape differs: " + "; ".join(delta[:8]))
        return

    ref_error, got_error = ref_reply.get("error", {}), got_reply.get("error", {})
    if ref_error.get("code") != got_error.get("code"):
        issues.append(f"{label}: error code differs (reference={_brief(ref_error.get('code'))}, candidate={_brief(got_error.get('code'))})")
    ref_payload, got_payload = ref_error.get("payload"), got_error.get("payload")
    if _canonical_shape(ref_payload, ignore_key_order) != _canonical_shape(got_payload, ignore_key_order):
        delta = differences(_canonical_shape(ref_payload, ignore_key_order), _canonical_shape(got_payload, ignore_key_order))
        issues.append(f"{label}: error payload marshal shape differs: " + "; ".join(delta[:8]))
    ref_text, got_text = _string_leaves(ref_payload), _string_leaves(got_payload)
    if ref_text != got_text:
        issues.append(f"{label}: error text differs (reference={_brief(ref_text)}, candidate={_brief(got_text)})")


def _notification_payload(record):
    if record.get("type") == "Notification":
        return {key: record[key] for key in ("args", "kwargs", "prefix", "named_payload") if key in record}
    value = record.get("payload")
    if record.get("type") in SESSION_TYPES and isinstance(value, dict) and value.get("$tuple"):
        # The first value is the session id. Its exact value may differ between runs.
        value = {"$tuple": [shape(value["$tuple"][0]), *value["$tuple"][1:]]}
    return {"payload": value}


def _notification_signature(record, ignore_volatile):
    return (record.get("type"), _normal_service(record.get("service"), ignore_volatile), record.get("method"))


def compare_all(reference_records, candidate_records, *, ignore_volatile, ignore_key_order=False, ignore_notification_order=False):
    """Report every per-call reply difference and every ordered notification difference."""
    reference_records, candidate_records = _comparison_connections(reference_records, candidate_records)
    ref_calls, ref_replies = _capture_calls(reference_records)
    got_calls, got_replies = _capture_calls(candidate_records)
    issues = []
    total_ref = sum(map(len, ref_calls.values()))
    total_got = sum(map(len, got_calls.values()))
    print(f"calls: reference={total_ref}, candidate={total_got}")

    for conn in sorted(set(ref_calls) | set(got_calls), key=lambda item: (item is None, item)):
        ref = ref_calls.get(conn, [])
        got = got_calls.get(conn, [])
        ref_sigs = [_call_signature(rec, ignore_volatile) for rec in ref]
        got_sigs = [_call_signature(rec, ignore_volatile) for rec in got]
        matcher = SequenceMatcher(None, ref_sigs, got_sigs, autojunk=False)
        for tag, i1, i2, j1, j2 in matcher.get_opcodes():
            if tag == "equal":
                pairs = zip(range(i1, i2), range(j1, j2))
            elif tag == "replace":
                paired = min(i2 - i1, j2 - j1)
                pairs = zip(range(i1, i1 + paired), range(j1, j1 + paired))
            else:
                pairs = ()
            for ri, gi in pairs:
                ref_call, got_call = ref[ri], got[gi]
                ref_signature, got_signature = ref_sigs[ri], got_sigs[gi]
                call_label = f"{_connection_label(conn)} #{ri + 1} {ref_signature[0]}.{ref_signature[1]}"
                local = []
                if ref_signature != got_signature:
                    local.append(f"call identity/order differs (reference={ref_signature}, candidate={got_signature})")
                ref_args, got_args = ref_call.get("args"), got_call.get("args")
                if _canonical_shape(ref_args, ignore_key_order) != _canonical_shape(got_args, ignore_key_order):
                    delta = differences(_canonical_shape(ref_args, ignore_key_order), _canonical_shape(got_args, ignore_key_order))
                    local.append("request argument marshal shape differs: " + "; ".join(delta[:8]))

                ref_key = (conn, ref_call.get("call_id"))
                got_key = (conn, got_call.get("call_id"))
                ref_for_call = ref_replies.get(ref_key, [])
                got_for_call = got_replies.get(got_key, [])
                if len(ref_for_call) != len(got_for_call):
                    local.append(f"reply count differs (reference={len(ref_for_call)}, candidate={len(got_for_call)})")
                for index in range(max(len(ref_for_call), len(got_for_call))):
                    _compare_call_reply(
                        ref_for_call[index] if index < len(ref_for_call) else None,
                        got_for_call[index] if index < len(got_for_call) else None,
                        ignore_key_order=ignore_key_order,
                        label=f"{call_label} reply #{index + 1}",
                        issues=local,
                    )
                if local:
                    issues.extend(f"{call_label}: {detail}" for detail in local)
                    print(f"  DIFF {call_label}")
                    for detail in local:
                        print(f"    - {detail}")
                else:
                    reply_kind = ",".join(_reply_summary(reply) for reply in ref_for_call) or "missing"
                    print(f"  SAME {call_label} reply={reply_kind}")

            if tag in ("delete", "replace"):
                for ri in range(i1 + (min(i2 - i1, j2 - j1) if tag == "replace" else 0), i2):
                    rec = ref[ri]
                    label = f"{_connection_label(conn)} reference-only #{ri + 1} {ref_sigs[ri][0]}.{ref_sigs[ri][1]}"
                    packets = ref_replies.get((conn, rec.get("call_id")), [])
                    detail = f"request missing from candidate; reply={_reply_summary(packets[0] if packets else None)}"
                    issues.append(f"{label}: {detail}")
                    print(f"  DIFF {label}\n    - {detail}")
            if tag in ("insert", "replace"):
                for gi in range(j1 + (min(i2 - i1, j2 - j1) if tag == "replace" else 0), j2):
                    rec = got[gi]
                    label = f"{_connection_label(conn)} candidate-only #{gi + 1} {got_sigs[gi][0]}.{got_sigs[gi][1]}"
                    packets = got_replies.get((conn, rec.get("call_id")), [])
                    detail = f"unexpected request; reply={_reply_summary(packets[0] if packets else None)}"
                    issues.append(f"{label}: {detail}")
                    print(f"  DIFF {label}\n    - {detail}")

    for side, calls, replies in (("reference", ref_calls, ref_replies), ("candidate", got_calls, got_replies)):
        request_keys = {
            (conn, record.get("call_id"))
            for conn, records in calls.items()
            for record in records
        }
        for key, packets in sorted(replies.items(), key=lambda item: (item[0][0] is None, item[0][0], item[0][1] is None, item[0][1])):
            if key in request_keys:
                continue
            for index, packet in enumerate(packets, start=1):
                detail = f"{side} orphan reply #{index} {_connection_label(key[0])} call_id={key[1]} type={_reply_summary(packet)}"
                print(f"  DIFF {detail}")
                issues.append(detail)

    ref_notices = defaultdict(list)
    got_notices = defaultdict(list)
    for records, target in ((reference_records, ref_notices), (candidate_records, got_notices)):
        for rec in records:
            if rec.get("stage") == "macho" and rec.get("type") in NOTIFICATION_TYPES:
                target[rec.get("_compare_conn", rec.get("conn"))].append(rec)
        for conn in target:
            target[conn].sort(key=lambda rec: rec.get("seq", 0))

    print("notifications:")
    notice_diffs = 0
    for conn in sorted(set(ref_notices) | set(got_notices), key=lambda item: (item is None, item)):
        ref = ref_notices.get(conn, [])
        got = got_notices.get(conn, [])
        if ignore_notification_order:
            key = lambda rec: json.dumps([_notification_signature(rec, ignore_volatile),
                                          _canonical_shape(_notification_payload(rec), ignore_key_order)],
                                         sort_keys=True, default=str)
            ref, got = sorted(ref, key=key), sorted(got, key=key)
        count = max(len(ref), len(got))
        for index in range(count):
            ref_rec = ref[index] if index < len(ref) else None
            got_rec = got[index] if index < len(got) else None
            if ref_rec is None or got_rec is None:
                side = "reference" if got_rec is None else "candidate"
                record = ref_rec if ref_rec is not None else got_rec
                sig = _notification_signature(record, ignore_volatile)
                print(f"  DIFF {_connection_label(conn)} notification #{index + 1}: {side} only {sig}")
                issues.append(f"{_connection_label(conn)} notification #{index + 1}: {side} only {sig}")
                notice_diffs += 1
                continue
            ref_sig = _notification_signature(ref_rec, ignore_volatile)
            got_sig = _notification_signature(got_rec, ignore_volatile)
            label = f"{_connection_label(conn)} notification #{index + 1} {ref_sig[2] or ref_sig[0]}"
            if ref_sig != got_sig:
                detail = f"notification name/order differs (reference={ref_sig}, candidate={got_sig})"
                print(f"  DIFF {label}: {detail}")
                issues.append(f"{label}: {detail}")
                notice_diffs += 1
                continue
            ref_payload = _canonical_shape(_notification_payload(ref_rec), ignore_key_order)
            got_payload = _canonical_shape(_notification_payload(got_rec), ignore_key_order)
            if ref_payload != got_payload:
                delta = differences(ref_payload, got_payload)
                detail = "notification marshal shape differs: " + "; ".join(delta[:8])
                print(f"  DIFF {label}: {detail}")
                issues.append(f"{label}: {detail}")
                notice_diffs += 1
            else:
                print(f"  SAME {label}")

    if issues:
        print(f"differences: {len(issues)} call/reply or notification issue(s)")
        return 1
    print(f"identical: {total_ref} calls, notification names/order and marshal shapes match")
    return 0


def cmd_diff(args):
    options = {"ignore_key_order": args.ignore_key_order, "ignore_notification_order": args.ignore_notification_order}
    reference_records, candidate_records = load(args.reference), load(args.candidate)
    if not args.first:
        return compare_all(
            reference_records,
            candidate_records,
            ignore_volatile=args.ignore_volatile,
            ignore_key_order=args.ignore_key_order,
            ignore_notification_order=args.ignore_notification_order,
        )

    reference = events(reference_records, args.ignore_volatile, **options)
    candidate = events(candidate_records, args.ignore_volatile, **options)
    mode = "volatile fields ignored" if args.ignore_volatile else "exact values"
    found = compare(reference, candidate, args.ignore_volatile)
    if found is None:
        print(f"identical: {len(reference[0])} client calls and {len(reference[1])} server events, {mode}")
        return 0
    stream, index, kind, details, at_a, at_b, total = found
    print(f"first divergence at event {index} of {total} in {stream} ({kind}; {mode})")
    print(f"  reference: {_brief(at_a, 400) if at_a is not None else '(none)'}")
    print(f"  candidate: {_brief(at_b, 400) if at_b is not None else '(none)'}")
    for line in details:
        print(f"  - {line}")
    return 1


