    public async Task<KillRightActionResult> ActivateKillRightAsync(
        long killRightId,
        long activatorCharacterId,
        long nowUnixMs,
        CancellationToken cancellationToken = default)
    {
        if (killRightId <= 0 || activatorCharacterId <= 0 || nowUnixMs <= 0)
        {
            return new(null, null, "NoValidKillRight");
        }
        await using var connection = await _source.OpenConnectionAsync(cancellationToken);
        await using var transaction = await connection.BeginTransactionAsync(cancellationToken);
        var right = await LockKillRightAsync(connection, transaction, killRightId, cancellationToken);
        if (right is null || right.OwnerCharacterId != activatorCharacterId)
        {
            return new(null, null, "NoValidKillRight");
        }
        if (right.ExpiresAtUnixMs <= nowUnixMs)
        {
            return new(null, null, "KillRightExpired");
        }
        var activation = await CreateKillRightActivationAsync(
            connection, transaction, right, activatorCharacterId, nowUnixMs, 0m, "activate", cancellationToken);
        await transaction.CommitAsync(cancellationToken);
        return new(right, activation, null);
    }

    public async Task<KillRightActionResult> BuyKillRightAsync(
        long killRightId,
        long buyerCharacterId,
        IReadOnlyCollection<long> buyerOwnerIds,
        decimal? expectedPrice,
        long nowUnixMs,
        KillRightPayment? payment,
        CancellationToken cancellationToken = default)
    {
        if (killRightId <= 0 || buyerCharacterId <= 0 || nowUnixMs <= 0
            || expectedPrice is < 0 || expectedPrice is { } amount && decimal.Round(amount, 2) != amount)
        {
            return new(null, null, "KillRightNotForSale");
        }
        await using var connection = await _source.OpenConnectionAsync(cancellationToken);
        await using var transaction = await connection.BeginTransactionAsync(cancellationToken);
        var right = await LockKillRightAsync(connection, transaction, killRightId, cancellationToken);
        if (right is null || right.OwnerCharacterId == buyerCharacterId)
        {
            return new(null, null, "NoValidKillRight");
        }
        if (right.ExpiresAtUnixMs <= nowUnixMs)
        {
            return new(null, null, "KillRightExpired");
        }
        if (right.SalePrice is not { } price)
        {
            return new(null, null, "KillRightNotForSale");
        }
        if (right.RestrictedToOwnerId is { } restrictedTo && !buyerOwnerIds.Contains(restrictedTo))
        {
            return new(null, null, "NoValidKillRight");
        }
        if (expectedPrice is { } quotedPrice && quotedPrice != price)
        {
            return new(null, null, "KillRightNotForSale");
        }

        var activation = await CreateKillRightActivationAsync(
            connection, transaction, right, buyerCharacterId, nowUnixMs, price, "buy", cancellationToken);
        if (price > 0)
        {
            if (payment is null)
            {
                await transaction.RollbackAsync(cancellationToken);
                return new(null, null, "PaymentFailed", price);
            }
            var paymentResult = await payment(
                connection, transaction, activation.ActivationId, buyerCharacterId,
                right.OwnerCharacterId, price, nowUnixMs, cancellationToken);
            if (paymentResult != KillRightPaymentResult.Paid)
            {
                await transaction.RollbackAsync(cancellationToken);
                return new(null, null, paymentResult == KillRightPaymentResult.InsufficientFunds
                    ? "NotEnoughMoney"
                    : "PaymentFailed", price);
            }
        }
        await transaction.CommitAsync(cancellationToken);
        return new(right, activation, null);
    }

