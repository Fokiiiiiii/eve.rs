CREATE TABLE events (
    event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id bigint NOT NULL,
    creator_id bigint NOT NULL,
    tag smallint NOT NULL CHECK (tag IN (1, 2, 4, 8, 16)),
    event_date_time bigint NOT NULL,
    duration_minutes integer CHECK (duration_minutes IS NULL OR duration_minutes >= 0),
    title text NOT NULL,
    event_text text NOT NULL,
    importance smallint NOT NULL DEFAULT 0,
    date_modified bigint NOT NULL,
    is_deleted boolean NOT NULL DEFAULT false,
    auto_event_type integer,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX events_owner_time ON events (owner_id, event_date_time);
CREATE INDEX events_time ON events (event_date_time);

CREATE TABLE responses (
    event_id bigint NOT NULL REFERENCES events (event_id) ON DELETE CASCADE,
    character_id bigint NOT NULL,
    status smallint NOT NULL CHECK (status BETWEEN 0 AND 5),
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (event_id, character_id)
);

CREATE INDEX responses_character_event ON responses (character_id, event_id);
