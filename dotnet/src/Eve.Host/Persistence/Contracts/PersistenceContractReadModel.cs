                is_corporation_issued boolean NOT NULL DEFAULT false,
                acceptor_id bigint NOT NULL DEFAULT 0 CHECK (acceptor_id >= 0),
                assignee_id bigint NOT NULL DEFAULT 0 CHECK (assignee_id >= 0),
                contract_type smallint NOT NULL CHECK (contract_type BETWEEN 1 AND 3),
                status smallint NOT NULL CHECK (status BETWEEN 0 AND 10),
                start_station_id bigint NOT NULL DEFAULT 0 CHECK (start_station_id >= 0),
                end_station_id bigint NOT NULL DEFAULT 0 CHECK (end_station_id >= 0),
                date_accepted_filetime bigint NOT NULL DEFAULT 0,
