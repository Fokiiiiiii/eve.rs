using System.Text.RegularExpressions;
using Eve.Services.Core;
using Npgsql;

namespace Eve.Host.Persistence;

public sealed class PersistenceContractReadModel : IContractReadModel
{
    public const string DefaultSchema = "contracts";

    private const short Outstanding = 0;
    private const short InProgress = 1;
    private const short Rejected = 6;
    private const short Failed = 7;
    private const long FileTimeTicksPerDay = 864_000_000_000L;

    private readonly NpgsqlDataSource _source;
    private readonly string _schema;

    public PersistenceContractReadModel(NpgsqlDataSource source, string schema = DefaultSchema)
    {
        ArgumentNullException.ThrowIfNull(source);
        _source = source;
        _schema = $"\"{ValidateSchema(schema)}\"";
    }

    public static IReadOnlyList<Eve.Data.Migration> MigrationSet() =>
    [
        new Eve.Data.Migration("0001_contracts", """
