using System.Text;
using System.Text.RegularExpressions;
using Npgsql;

namespace Eve.Host.Xmpp;

internal sealed record XmppPlayerChannel(long Id, string DisplayName, long OwnerCharacterId, IReadOnlySet<long> InvitedCharacterIds)
{
    public string RoomName => $"player_{Id.ToString(System.Globalization.CultureInfo.InvariantCulture)}";

    public bool Allows(long characterId) => OwnerCharacterId == characterId || InvitedCharacterIds.Contains(characterId);
}

internal sealed class XmppPlayerChannelStore
{
    public const int MaxDisplayNameBytes = 128;
    private readonly NpgsqlDataSource _source;
    private readonly string _schema;
    private readonly object _gate = new();
    private readonly Dictionary<string, XmppPlayerChannel> _channels;

    private XmppPlayerChannelStore(NpgsqlDataSource source, string schema, Dictionary<string, XmppPlayerChannel> channels)
    {
        _source = source;
        _schema = schema;
        _channels = channels;
    }

    public static async Task<XmppPlayerChannelStore> OpenAsync(NpgsqlDataSource source, string schema, CancellationToken cancellationToken = default)
    {
        if (!Regex.IsMatch(schema, "^[a-z_][a-z0-9_]{0,62}$"))
            throw new ArgumentException($"not a usable schema name: {schema}", nameof(schema));
        await using (var createSchema = source.CreateCommand($"CREATE SCHEMA IF NOT EXISTS {schema}"))
            await createSchema.ExecuteNonQueryAsync(cancellationToken);
        await using (var createTable = source.CreateCommand($"CREATE TABLE IF NOT EXISTS {schema}.player_channels (channel_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, display_name text NOT NULL CHECK (char_length(display_name) BETWEEN 1 AND 128), owner_character_id bigint NOT NULL CHECK (owner_character_id > 0), invited_character_ids bigint[] NOT NULL DEFAULT '{{}}', created_ms bigint NOT NULL DEFAULT ((extract(epoch FROM clock_timestamp()) * 1000)::bigint))"))
            await createTable.ExecuteNonQueryAsync(cancellationToken);

        var channels = new Dictionary<string, XmppPlayerChannel>(StringComparer.Ordinal);
        await using (var command = source.CreateCommand($"SELECT channel_id,display_name,owner_character_id,invited_character_ids FROM {schema}.player_channels ORDER BY channel_id"))
        await using (var reader = await command.ExecuteReaderAsync(cancellationToken))
        {
            while (await reader.ReadAsync(cancellationToken))
            {
                var id = reader.GetInt64(0);
                var roomName = $"player_{id.ToString(System.Globalization.CultureInfo.InvariantCulture)}";
                var channel = new XmppPlayerChannel(id, reader.GetString(1), reader.GetInt64(2), reader.GetFieldValue<long[]>(3).ToHashSet());
                channels.Add(roomName, channel);
            }
        }
        return new XmppPlayerChannelStore(source, schema, channels);
    }

    public async Task<XmppPlayerChannel?> CreateAsync(long ownerCharacterId, string displayName, CancellationToken cancellationToken = default)
    {
        displayName = displayName.Trim();
        if (ownerCharacterId <= 0 || displayName.Length == 0 || Encoding.UTF8.GetByteCount(displayName) > MaxDisplayNameBytes
            || displayName.Any(char.IsControl))
            return null;

        await using var command = _source.CreateCommand($"INSERT INTO {_schema}.player_channels(display_name,owner_character_id) VALUES ($1,$2) RETURNING channel_id");
        command.Parameters.AddWithValue(displayName);
        command.Parameters.AddWithValue(ownerCharacterId);
        var id = (long)(await command.ExecuteScalarAsync(cancellationToken) ?? throw new InvalidOperationException("player channel insert returned no id"));
        var channel = new XmppPlayerChannel(id, displayName, ownerCharacterId, new HashSet<long>());
        lock (_gate)
            _channels.Add(channel.RoomName, channel);
        return channel;
    }

    public async Task<bool> SetOwnerAsync(string roomName, long ownerCharacterId, CancellationToken cancellationToken = default)
    {
        if (ownerCharacterId <= 0 || !TryId(roomName, out var id)) return false;
        await using var command = _source.CreateCommand($"UPDATE {_schema}.player_channels SET owner_character_id=$2, invited_character_ids=array_remove(invited_character_ids,$2) WHERE channel_id=$1");
        command.Parameters.AddWithValue(id);
        command.Parameters.AddWithValue(ownerCharacterId);
        if (await command.ExecuteNonQueryAsync(cancellationToken) != 1) return false;
        lock (_gate)
        {
            if (_channels.TryGetValue(roomName, out var channel))
            {
                var invited = channel.InvitedCharacterIds.ToHashSet();
                invited.Remove(ownerCharacterId);
                _channels[roomName] = channel with { OwnerCharacterId = ownerCharacterId, InvitedCharacterIds = invited };
            }
        }
        return true;
    }

    public async Task<bool> InviteAsync(string roomName, long characterId, CancellationToken cancellationToken = default)
    {
        if (characterId <= 0 || !TryId(roomName, out var id)) return false;
        await using var command = _source.CreateCommand($"UPDATE {_schema}.player_channels SET invited_character_ids=array_append(invited_character_ids,$2) WHERE channel_id=$1 AND owner_character_id<>$2 AND NOT ($2=ANY(invited_character_ids))");
        command.Parameters.AddWithValue(id);
        command.Parameters.AddWithValue(characterId);
        var changed = await command.ExecuteNonQueryAsync(cancellationToken);
        if (changed == 0)
        {
            lock (_gate)
                return _channels.TryGetValue(roomName, out var current) && current.Allows(characterId);
        }
        lock (_gate)
        {
            if (_channels.TryGetValue(roomName, out var channel))
            {
                var invited = channel.InvitedCharacterIds.ToHashSet();
                invited.Add(characterId);
                _channels[roomName] = channel with { InvitedCharacterIds = invited };
            }
        }
        return true;
    }

    public XmppPlayerChannel? Get(string roomName)
    {
        lock (_gate) return _channels.GetValueOrDefault(roomName);
    }

    public bool CanJoin(string roomName, long characterId)
    {
        lock (_gate) return _channels.TryGetValue(roomName, out var channel) && channel.Allows(characterId);
    }

    public IReadOnlyList<XmppPlayerChannel> AvailableTo(long characterId)
    {
        lock (_gate) return _channels.Values.Where(channel => channel.Allows(characterId)).OrderBy(channel => channel.Id).ToArray();
    }

    private static bool TryId(string roomName, out long id)
    {
        id = 0;
        return roomName.StartsWith("player_", StringComparison.Ordinal)
            && long.TryParse(roomName.AsSpan("player_".Length), System.Globalization.NumberStyles.None, System.Globalization.CultureInfo.InvariantCulture, out id)
            && id > 0;
    }
}
