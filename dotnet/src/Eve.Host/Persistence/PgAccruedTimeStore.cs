using System.Text.RegularExpressions;
using Eve.Marshal;
using Npgsql;

namespace Eve.Host.Persistence;

public sealed class PgAccruedTimeStore(NpgsqlDataSource source, string schema = "eve_login")
{
    public const string DefaultSchema = "eve_login";
    private static readonly Regex SafeSchema = new("^[a-z_][a-z0-9_]{0,62}$", RegexOptions.CultureInvariant);
    private readonly string _schema = SafeSchema.IsMatch(schema) ? schema : throw new ArgumentException("Invalid schema name.", nameof(schema));

    public async Task MigrateAsync(CancellationToken cancellationToken = default)
    {
        await using var command = source.CreateCommand($"""
            CREATE SCHEMA IF NOT EXISTS {_schema};
            CREATE TABLE IF NOT EXISTS {_schema}.accrued_sessions (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                account_id bigint NOT NULL CHECK (account_id > 0),
                started_ticks bigint NOT NULL,
                ended_ticks bigint NULL CHECK (ended_ticks IS NULL OR ended_ticks >= started_ticks)
            );
            CREATE INDEX IF NOT EXISTS accrued_sessions_account_id_id_idx
                ON {_schema}.accrued_sessions (account_id, id);
            """);
        await command.ExecuteNonQueryAsync(cancellationToken);
    }

    public async Task<long> OpenAsync(long accountId, long startedTicks, CancellationToken cancellationToken = default)
    {
        if (accountId <= 0)
            throw new ArgumentOutOfRangeException(nameof(accountId));
        await using var command = source.CreateCommand($"""
            INSERT INTO {_schema}.accrued_sessions (account_id, started_ticks)
            VALUES (@account_id, @started_ticks)
            RETURNING id
            """);
        command.Parameters.AddWithValue("account_id", accountId);
        command.Parameters.AddWithValue("started_ticks", startedTicks);
        return (long)(await command.ExecuteScalarAsync(cancellationToken)
            ?? throw new InvalidOperationException("The accrued session insert returned no row."));
    }

    public async Task CloseAsync(long id, long endedTicks, CancellationToken cancellationToken = default)
    {
        await using var command = source.CreateCommand($"""
            UPDATE {_schema}.accrued_sessions
            SET ended_ticks = GREATEST(started_ticks, @ended_ticks)
            WHERE id = @id AND ended_ticks IS NULL
            """);
        command.Parameters.AddWithValue("id", id);
        command.Parameters.AddWithValue("ended_ticks", endedTicks);
        await command.ExecuteNonQueryAsync(cancellationToken);
    }

    public async Task<PyValue> ReadWireValueAsync(long accountId, long nowTicks, CancellationToken cancellationToken = default)
    {
        if (accountId <= 0)
            return new PyList([]);
        var rows = new List<PyValue>();
        await using var command = source.CreateCommand($"""
            SELECT id, started_ticks, COALESCE(ended_ticks, @now_ticks)
            FROM {_schema}.accrued_sessions
            WHERE account_id = @account_id
            ORDER BY id
            LIMIT 2048
            """);
        command.Parameters.AddWithValue("account_id", accountId);
        command.Parameters.AddWithValue("now_ticks", nowTicks);
        await using var reader = await command.ExecuteReaderAsync(cancellationToken);
        while (await reader.ReadAsync(cancellationToken))
        {
            rows.Add(new PyTuple([
                new PyLong(reader.GetInt64(0)),
                new PyLong(reader.GetInt64(1)),
                new PyLong(reader.GetInt64(2)),
            ]));
        }
        return new PyList(rows);
    }
}
