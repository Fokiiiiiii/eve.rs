    public static Task MigrateAsync(
        NpgsqlDataSource source,
        string schema = DefaultSchema,
        CancellationToken cancellationToken = default) =>
        Eve.Data.Migrations.ApplyAsync(source, ValidateSchema(schema), MigrationSet(), cancellationToken);

    public async ValueTask<ContractLoginInfo> GetLoginInfoAsync(
        long characterId,
        long corporationId,
        long allianceId,
        long nowFileTime,
        CancellationToken cancellationToken)
    {
        if (characterId <= 0)
            throw new ArgumentOutOfRangeException(nameof(characterId));
        if (corporationId < 0 || allianceId < 0)
            throw new ArgumentOutOfRangeException(nameof(corporationId));

        var attention = new List<ContractNeedsAttentionRow>();
        var inProgress = new List<ContractInProgressRow>();
        var assigned = new List<ContractAssignedToMeRow>();
        await using var connection = await _source.OpenConnectionAsync(cancellationToken);
        await using var command = new NpgsqlCommand($"""
            SELECT contract_id, issuer_id, issuer_corporation_id, is_corporation_issued,
                   acceptor_id, assignee_id, status, start_station_id, end_station_id,
                   date_accepted_filetime, date_expired_filetime, num_days
            FROM {_schema}.contract_records
            WHERE (status IN ($4, $5) AND
                   (issuer_id = $1 OR acceptor_id = $1 OR acceptor_id = $2 OR
                    (is_corporation_issued AND issuer_corporation_id = $2)))
               OR (status = $6 AND date_expired_filetime < $3 AND
                   ((NOT is_corporation_issued AND issuer_id = $1) OR
                    (is_corporation_issued AND issuer_corporation_id = $2)))
               OR (status = $7 AND acceptor_id = ANY($8))
               OR (status = $6 AND assignee_id = ANY($9) AND date_expired_filetime >= $3)
            ORDER BY contract_id
            """, connection);
        command.Parameters.AddWithValue(characterId);
        command.Parameters.AddWithValue(corporationId);
        command.Parameters.AddWithValue(nowFileTime);
        command.Parameters.AddWithValue(Rejected);
        command.Parameters.AddWithValue(Failed);
        command.Parameters.AddWithValue(Outstanding);
        command.Parameters.AddWithValue(InProgress);
        command.Parameters.AddWithValue(new[] { characterId, corporationId }.Where(id => id > 0).Distinct().ToArray());
        command.Parameters.AddWithValue(new[] { characterId, corporationId, allianceId }.Where(id => id > 0).Distinct().ToArray());

        await using var reader = await command.ExecuteReaderAsync(cancellationToken);
        while (await reader.ReadAsync(cancellationToken))
        {
            var contractId = reader.GetInt64(0);
            var issuerId = reader.GetInt64(1);
            var issuerCorporationId = reader.GetInt64(2);
            var isCorporationIssued = reader.GetBoolean(3);
            var acceptorId = reader.GetInt64(4);
            var assigneeId = reader.GetInt64(5);
            var status = reader.GetInt16(6);
            var startStationId = reader.GetInt64(7);
            var endStationId = reader.GetInt64(8);
            var dateAccepted = reader.GetInt64(9);
            var dateExpired = reader.GetInt64(10);
            var numDays = reader.GetInt32(11);

            if (status is Rejected or Failed || status == Outstanding && dateExpired < nowFileTime)
            {
                var personal = (!isCorporationIssued && issuerId == characterId) || acceptorId == characterId;
                var corporation = corporationId > 0 &&
                    ((isCorporationIssued && issuerCorporationId == corporationId) || acceptorId == corporationId);
                if (personal) attention.Add(new ContractNeedsAttentionRow(contractId, 0));
                if (corporation) attention.Add(new ContractNeedsAttentionRow(contractId, 1));
            }

            if (status == InProgress && (acceptorId == characterId || acceptorId == corporationId))
            {
                var expires = checked(dateAccepted + checked((long)numDays * FileTimeTicksPerDay));
                inProgress.Add(new ContractInProgressRow(contractId, startStationId, endStationId, expires));
            }

            if (status == Outstanding && dateExpired >= nowFileTime &&
                (assigneeId == characterId || assigneeId == corporationId || allianceId > 0 && assigneeId == allianceId))
                assigned.Add(new ContractAssignedToMeRow(contractId, issuerId));
        }

        return new ContractLoginInfo(attention, inProgress, assigned);
    }

    public async ValueTask<ContractEscrowSummary> GetMyContractEscrowAsync(
        long characterId,
        long corporationId,
        CancellationToken cancellationToken)
    {
        if (characterId <= 0)
            throw new ArgumentOutOfRangeException(nameof(characterId));
        if (corporationId < 0)
            throw new ArgumentOutOfRangeException(nameof(corporationId));

        await using var connection = await _source.OpenConnectionAsync(cancellationToken);
        await using var command = new NpgsqlCommand($"""
            SELECT COALESCE(SUM(c.reward_escrow), 0),
                   COALESCE(SUM(items.item_count), 0)::bigint
            FROM {_schema}.contract_records AS c
            LEFT JOIN LATERAL (
                SELECT COUNT(*) FILTER (WHERE in_crate OR is_package) AS item_count
                FROM {_schema}.contract_items
                WHERE contract_id = c.contract_id
            ) AS items ON true
            WHERE c.issuer_id = $1 OR (c.is_corporation_issued AND c.issuer_corporation_id = $2)
            """, connection);
        command.Parameters.AddWithValue(characterId);
        command.Parameters.AddWithValue(corporationId);
        await using var reader = await command.ExecuteReaderAsync(cancellationToken);
        if (!await reader.ReadAsync(cancellationToken))
            throw new InvalidOperationException("contract escrow aggregate did not return a row");
        return new ContractEscrowSummary(reader.GetDecimal(0), reader.GetInt64(1));
    }

    private static string ValidateSchema(string schema) => Regex.IsMatch(schema, "^[a-z_][a-z0-9_]{0,62}$")
        ? schema
        : throw new ArgumentException("not a usable schema name", nameof(schema));
}
