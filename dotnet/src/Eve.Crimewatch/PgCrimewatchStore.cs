                   created_at_ms, expires_at_ms, sale_price, restricted_to_owner_id
            FROM {schema}.kill_rights
            WHERE kill_right_id = $1 AND used_at_ms IS NULL
            FOR UPDATE
            """), killRightId);
        await using var row = await command.ExecuteReaderAsync(cancellationToken);
        return await row.ReadAsync(cancellationToken) ? ReadKillRight(row) : null;
    }

    private async Task<KillRightActivation> CreateKillRightActivationAsync(
        NpgsqlConnection connection,
        NpgsqlTransaction transaction,
        KillRight right,
        long activatorCharacterId,
        long nowUnixMs,
        decimal pricePaid,
        string activationKind,
        CancellationToken cancellationToken)
    {
        await using var command = Sql.Command(connection, transaction, Q("""
            INSERT INTO {schema}.kill_right_activations
                (kill_right_id, owner_character_id, target_character_id, activator_character_id,
                 activated_at_ms, expires_at_ms, price_paid, activation_kind)
            VALUES ($1, $2, $3, $4, $5, $6, $7, $8)
            RETURNING activation_id
            """), right.KillRightId, right.OwnerCharacterId, right.TargetCharacterId,
            activatorCharacterId, nowUnixMs, checked(nowUnixMs + 900_000L), pricePaid, activationKind);
        var id = (long)(await command.ExecuteScalarAsync(cancellationToken)
            ?? throw new InvalidOperationException("Kill right activation was not persisted."));
        return new(id, right.KillRightId, right.OwnerCharacterId, right.TargetCharacterId,
            activatorCharacterId, nowUnixMs, nowUnixMs + 900_000L, pricePaid, activationKind);
    }

    private static KillRight ReadKillRight(NpgsqlDataReader row) => new(
        row.GetInt64(0), row.GetInt64(1), row.GetInt64(2), row.GetInt64(3), row.GetInt64(4),
        row.GetInt64(5), row.IsDBNull(6) ? null : row.GetDecimal(6), row.IsDBNull(7) ? null : row.GetInt64(7));

    private static KillRightActivation ReadKillRightActivation(NpgsqlDataReader row) => new(
