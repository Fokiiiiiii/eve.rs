#!/usr/bin/env node
// Writes oracle/fixtures/wrecks/ship_wrecks.json: what the EVE.js reference's resolveShipWreckType answers for the published ships (category 6) and a
// sample of the NPC ships (category 11), so that the port in crates/eve-space/src/wreck_types.rs is checked against it.
//
//   SDE=.cache/sde/eve-online-static-data-<build>-jsonl EVEJS_DATA_ROOT=$PWD/.cache/ref EVEJS_GAMESTORE_DATA_DIR=$PWD/.cache/ref/gameStore/data \
//     node tools/dev/gen-ship-wrecks-fixture.js
"use strict";

const fs = require("fs");
const path = require("path");

const EVEJS = process.env.EVEJS || "/home/user/evejs-v0.12.9";
const SDE = process.env.SDE;
if (!SDE) {
  console.error("SDE (the directory of the SDE's JSONL files) is required");
  process.exit(2);
}
const OUT = path.join(__dirname, "..", "..", "oracle", "fixtures", "wrecks", "ship_wrecks.json");
const { resolveShipWreckType } = require(path.join(EVEJS, "server/src/space/wreckUtils"));

const rows = (name) =>
  fs.readFileSync(path.join(SDE, `${name}.jsonl`), "utf8").split("\n").filter(Boolean).map((line) => JSON.parse(line));

const category = new Map(rows("groups").map((g) => [g._key, g.categoryID]));
const types = rows("types").filter((t) => t.published !== false || category.get(t.groupID) === 6);
const ships = types.filter((t) => category.get(t.groupID) === 6 && t.published);
const npcs = types.filter((t) => category.get(t.groupID) === 11).filter((_, index) => index % 12 === 0);

const cases = [];
for (const type of [...ships, ...npcs]) {
  const wreck = resolveShipWreckType(type._key);
  cases.push({ shipTypeID: type._key, wreck: wreck ? { typeID: wreck.typeID, name: wreck.name, graphicID: wreck.graphicID || 0 } : null });
}
const commit = require("child_process").execSync("git rev-parse HEAD", { cwd: EVEJS }).toString().trim();
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, JSON.stringify({ note: "Generated by tools/dev/gen-ship-wrecks-fixture.js from the reference's resolveShipWreckType", referenceCommit: commit, cases }) + "\n");
console.log(`${cases.length} ships -> ${OUT}`);
