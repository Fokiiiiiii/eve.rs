#!/usr/bin/env node
// Writes oracle/fixtures/death/drop_counts.json: what the EVE.js reference's resolveStackDropCounts (server/src/services/killmail/deathOutcomeResolver.js)
// answers for stacks and single items of every size class, flags and options, so that the port in dotnet/src/Eve.Inventory/DeathOutcome.cs is held to it.
//
//   SDE=... EVEJS_DATA_ROOT=$PWD/.cache/ref EVEJS_GAMESTORE_DATA_DIR=$PWD/.cache/ref/gameStore/data node tools/dev/gen-death-outcome-fixture.js
"use strict";

const fs = require("fs");
const path = require("path");

const EVEJS = process.env.EVEJS || "/home/user/evejs-v0.12.9";
const OUT = path.join(__dirname, "..", "..", "oracle", "fixtures", "death", "drop_counts.json");
const { resolveStackDropCounts } = require(path.join(EVEJS, "server/src/services/killmail/deathOutcomeResolver"));

const seeds = ["ship:9988400002411:1790774257401", "ship:1:0", "death:42", "ship:2100000000123:134352478574010000", ""];
const itemIds = [1, 2, 9988400002412, 9988400002413, 2100000000123];
// the sizes on both sides of the per-unit roll limit (100), and the flags that are always destroyed (rigs 92-99, subsystems 125-132)
const quantities = [1, 2, 7, 50, 99, 100, 101, 102, 1000, 46_500_000, 2_000_000_000];
const flags = [0, 4, 5, 11, 19, 27, 91, 92, 95, 99, 100, 124, 125, 130, 132, 133];
const optionSets = [{}, { forceAllDestroyed: true }, { forceAllDropped: true }, { forceAllDestroyed: true, forceAllDropped: true }];

const cases = [];
for (const seed of seeds) {
  for (const itemID of itemIds) {
    for (const quantity of quantities) {
      for (const flag of flags) {
        for (const options of optionSets) {
          if (options.forceAllDestroyed || options.forceAllDropped) {
            if (flag !== 4 && flag !== 92) continue; // the options do not depend on the flag but for the always-destroyed ones
          }
          const { qtyDropped, qtyDestroyed } = resolveStackDropCounts({ itemID, quantity, flag }, seed, options);
          cases.push({ seed, itemID: String(itemID), quantity: String(quantity), flag, ...options, qtyDropped: String(qtyDropped), qtyDestroyed: String(qtyDestroyed) });
        }
      }
    }
  }
}
const commit = require("child_process").execSync("git rev-parse HEAD", { cwd: EVEJS }).toString().trim();
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, JSON.stringify({ note: "Generated by tools/dev/gen-death-outcome-fixture.js from the reference's resolveStackDropCounts", referenceCommit: commit, cases }) + "\n");
console.log(`${cases.length} cases -> ${OUT}`);
