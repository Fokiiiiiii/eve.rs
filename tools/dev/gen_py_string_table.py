#!/usr/bin/env python3
"""Generate evecli/string_table.py from the Rust string table.

The Rust file is itself generated from the JS reference (see oracle/PROVENANCE.md),
so the three implementations share one source of truth.

    python3 tools/dev/gen_py_string_table.py
"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parents[2]
source = (root / "crates/eve-marshal/src/string_table.rs").read_text()
entries = re.findall(r'^\s*"((?:[^"\\]|\\.)*)",\s*// (\d+)$', source, re.M)
assert [int(n) for _, n in entries] == list(range(1, len(entries) + 1)), "table is not 1..N in order"

out = root / "tools/headless-client/evecli/string_table.py"
lines = ["# @generated by tools/dev/gen_py_string_table.py. Do not edit by hand.", "",
         "# Marshal string table; wire indices are 1-based (index 1 is STRING_TABLE[0]).",
         "STRING_TABLE = ("]
lines += [f'    "{text}",  # {n}' for text, n in entries]
lines += [")", ""]
out.write_text("\n".join(lines))
print(f"wrote {len(entries)} entries to {out.relative_to(root)}")
